-- =============================================================
-- 003_user_verifications.sql
--
-- Stores identity verification information for Agro-Shield users.
--
-- Verification is separate from:
--   - user roles
--   - farming types
--   - learning progress
--   - farmer confirmation
--
-- A user may learn farming without being identity-verified.
-- =============================================================

CREATE TABLE IF NOT EXISTS user_verifications (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- =========================================================
    -- User
    -- =========================================================
    user_id INTEGER NOT NULL UNIQUE,

    -- =========================================================
    -- NIN Verification
    -- =========================================================
    nin TEXT,

    nin_verified BOOLEAN NOT NULL DEFAULT FALSE,

    nin_verification_reference TEXT,

    -- =========================================================
    -- Verification Status
    -- =========================================================
    verification_level TEXT NOT NULL DEFAULT 'unverified',

    -- =========================================================
    -- Verification Timestamp
    -- =========================================================
    verified_at TIMESTAMP,

    -- =========================================================
    -- Timestamp
    -- =========================================================
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- =========================================================
    -- Relationships
    -- =========================================================
    CONSTRAINT fk_user_verifications_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    -- =========================================================
    -- Validation
    -- =========================================================
    CONSTRAINT user_verifications_level_check
        CHECK (
            verification_level IN (
                'unverified',
                'pending',
                'verified',
                'rejected'
            )
        ),

    CONSTRAINT user_verifications_nin_check
        CHECK (
            nin IS NULL OR BTRIM(nin) <> ''
        ),

    CONSTRAINT user_verifications_reference_check
        CHECK (
            nin_verification_reference IS NULL
            OR BTRIM(nin_verification_reference) <> ''
        ),

    CONSTRAINT user_verifications_verified_at_check
        CHECK (
            (nin_verified = FALSE)
            OR (verified_at IS NOT NULL)
        )
);


-- =============================================================
-- Indexes
-- =============================================================

CREATE INDEX IF NOT EXISTS idx_user_verifications_user_id
ON user_verifications(user_id);

CREATE INDEX IF NOT EXISTS idx_user_verifications_level
ON user_verifications(verification_level);

CREATE INDEX IF NOT EXISTS idx_user_verifications_nin_verified
ON user_verifications(nin_verified);