-- =============================================================
-- 046_wallet_virtual_accounts.sql
--
-- One permanent NGN virtual funding account per user.
--
-- The identity document itself is never stored: only the kind of
-- document used and the consent that justified sharing it. tx_ref
-- is deterministic per user so a retry reuses the same reference
-- instead of opening a second account.
-- =============================================================

CREATE TABLE IF NOT EXISTS wallet_virtual_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id INTEGER NOT NULL UNIQUE,

    provider VARCHAR(30) NOT NULL DEFAULT 'flutterwave',

    tx_ref VARCHAR(100) NOT NULL UNIQUE,

    order_ref VARCHAR(100) NOT NULL DEFAULT '',

    provider_ref VARCHAR(100) NOT NULL DEFAULT '',

    account_number VARCHAR(20) NOT NULL DEFAULT '',

    bank_name TEXT NOT NULL DEFAULT '',

    account_name TEXT NOT NULL DEFAULT '',

    currency VARCHAR(3) NOT NULL DEFAULT 'NGN',

    status VARCHAR(20) NOT NULL DEFAULT 'pending',

    identity_kind VARCHAR(10) NOT NULL DEFAULT '',

    consent_version VARCHAR(40) NOT NULL DEFAULT '',

    consent_at TIMESTAMP,

    failure_reason TEXT NOT NULL DEFAULT '',

    last_checked_at TIMESTAMP,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_wallet_virtual_accounts_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE RESTRICT,

    CONSTRAINT wallet_virtual_accounts_provider_nonblank
        CHECK (BTRIM(provider) <> ''),

    CONSTRAINT wallet_virtual_accounts_tx_ref_nonblank
        CHECK (BTRIM(tx_ref) <> ''),

    CONSTRAINT wallet_virtual_accounts_status_check
        CHECK (status IN ('pending', 'active', 'failed')),

    CONSTRAINT wallet_virtual_accounts_identity_kind_check
        CHECK (identity_kind IN ('', 'bvn', 'nin')),

    CONSTRAINT wallet_virtual_accounts_account_number_check
        CHECK (account_number = '' OR account_number ~ '^[0-9]{10}$'),

    CONSTRAINT wallet_virtual_accounts_active_details_check
        CHECK (
            status <> 'active'
            OR (
                account_number <> ''
                AND BTRIM(bank_name) <> ''
                AND BTRIM(account_name) <> ''
            )
        )
);

CREATE INDEX IF NOT EXISTS idx_wallet_virtual_accounts_status
    ON wallet_virtual_accounts(status);

CREATE INDEX IF NOT EXISTS idx_wallet_virtual_accounts_last_checked
    ON wallet_virtual_accounts(last_checked_at);
