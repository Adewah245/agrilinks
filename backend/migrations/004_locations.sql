-- =============================================================
-- 004_locations.sql
--
-- Defines the Agro-Shield geographical hierarchy.
--
-- Nigeria:
--
--     State
--        ↓
--      LGA
--        ↓
--   Community
--
-- Location information can later support:
--   - Marketplace
--   - Farmer profiles
--   - Learning recommendations
--   - AI farming guidance
--   - Farming suitability
--   - Local agricultural information
-- =============================================================


-- =============================================================
-- STATES
-- =============================================================

CREATE TABLE IF NOT EXISTS states (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name TEXT NOT NULL UNIQUE,

    CONSTRAINT states_name_nonblank
        CHECK (BTRIM(name) <> '')
);


-- =============================================================
-- LOCAL GOVERNMENT AREAS
-- =============================================================

CREATE TABLE IF NOT EXISTS lgas (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    state_id INTEGER NOT NULL,

    name TEXT NOT NULL,

    CONSTRAINT fk_lgas_state
        FOREIGN KEY (state_id)
        REFERENCES states(id)
        ON DELETE CASCADE,

    CONSTRAINT unique_lga_per_state
        UNIQUE (state_id, name),

    CONSTRAINT lgas_name_nonblank
        CHECK (BTRIM(name) <> '')
);


-- =============================================================
-- COMMUNITIES
-- =============================================================

CREATE TABLE IF NOT EXISTS communities (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    lga_id INTEGER NOT NULL,

    name TEXT NOT NULL,

    CONSTRAINT fk_communities_lga
        FOREIGN KEY (lga_id)
        REFERENCES lgas(id)
        ON DELETE CASCADE,

    CONSTRAINT unique_community_per_lga
        UNIQUE (lga_id, name),

    CONSTRAINT communities_name_nonblank
        CHECK (BTRIM(name) <> '')
);


-- =============================================================
-- INDEXES
-- =============================================================

CREATE INDEX IF NOT EXISTS idx_states_name
ON states(name);


CREATE INDEX IF NOT EXISTS idx_lgas_state_id
ON lgas(state_id);


CREATE INDEX IF NOT EXISTS idx_lgas_name
ON lgas(name);


CREATE INDEX IF NOT EXISTS idx_communities_lga_id
ON communities(lga_id);


CREATE INDEX IF NOT EXISTS idx_communities_name
ON communities(name);