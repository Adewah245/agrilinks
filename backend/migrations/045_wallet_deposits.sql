-- =============================================================
-- 045_wallet_deposits.sql
--
-- One wallet funding attempt made through a payment provider.
--
-- provider identifies the vendor that owns the reference. The
-- provider transaction id is unique within that provider, not
-- globally, because separate vendors are not required to avoid
-- colliding identifiers.
-- =============================================================

CREATE TABLE IF NOT EXISTS wallet_deposits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    wallet_id INTEGER NOT NULL,

    provider VARCHAR(30) NOT NULL DEFAULT 'flutterwave',

    reference VARCHAR(100) NOT NULL UNIQUE,

    provider_transaction_id VARCHAR(100),

    amount NUMERIC(20,2) NOT NULL,

    currency VARCHAR(3) NOT NULL DEFAULT 'NGN',

    verified_amount NUMERIC(20,2),

    verified_currency VARCHAR(3),

    status VARCHAR(20) NOT NULL DEFAULT 'pending',

    failure_reason TEXT,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_wallet_deposits_wallet
        FOREIGN KEY (wallet_id)
        REFERENCES wallets(id)
        ON DELETE RESTRICT,

    CONSTRAINT wallet_deposits_provider_nonblank
        CHECK (BTRIM(provider) <> ''),

    CONSTRAINT wallet_deposits_reference_nonblank
        CHECK (BTRIM(reference) <> ''),

    CONSTRAINT wallet_deposits_amount_check
        CHECK (amount > 0),

    CONSTRAINT wallet_deposits_currency_check
        CHECK (BTRIM(currency) <> ''),

    CONSTRAINT wallet_deposits_verified_amount_check
        CHECK (verified_amount IS NULL OR verified_amount > 0),

    CONSTRAINT wallet_deposits_status_check
        CHECK (
            status IN (
                'pending',
                'processing',
                'successful',
                'failed',
                'expired',
                'reversed'
            )
        ),

    CONSTRAINT wallet_deposits_provider_transaction_unique
        UNIQUE (provider, provider_transaction_id)
);

CREATE INDEX IF NOT EXISTS idx_wallet_deposits_wallet_time
    ON wallet_deposits(wallet_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_wallet_deposits_status_time
    ON wallet_deposits(status, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_wallet_deposits_provider_reference
    ON wallet_deposits(provider, reference);
