CREATE TABLE IF NOT EXISTS farm_tasks (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    farming_activity_id INTEGER NOT NULL,

    assigned_to INTEGER,

    created_by INTEGER NOT NULL,

    title TEXT NOT NULL,
    description TEXT,

    task_type TEXT NOT NULL,

    priority TEXT NOT NULL DEFAULT 'normal',

    status TEXT NOT NULL DEFAULT 'pending',

    scheduled_date DATE,
    due_date DATE,

    completed_at TIMESTAMP,

    notes TEXT,

    metadata JSONB,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    FOREIGN KEY (farming_activity_id)
        REFERENCES farming_activities(id)
        ON DELETE CASCADE,

    FOREIGN KEY (assigned_to)
        REFERENCES users(id)
        ON DELETE SET NULL,

    FOREIGN KEY (created_by)
        REFERENCES users(id)
        ON DELETE RESTRICT,

    CHECK (TRIM(title) <> ''),

    CHECK (
        description IS NULL
        OR TRIM(description) <> ''
    ),

    CHECK (TRIM(task_type) <> ''),

    CHECK (
        task_type IN (
            'feeding',
            'watering',
            'fertilization',
            'weeding',
            'pest_control',
            'vaccination',
            'medication',
            'cleaning',
            'inspection',
            'stocking',
            'breeding',
            'harvesting',
            'equipment_maintenance',
            'record_update',
            'other'
        )
    ),

    CHECK (
        priority IN (
            'low',
            'normal',
            'high',
            'urgent'
        )
    ),

    CHECK (
        status IN (
            'pending',
            'in_progress',
            'completed',
            'cancelled',
            'overdue'
        )
    ),

    CHECK (
        due_date IS NULL
        OR scheduled_date IS NULL
        OR due_date >= scheduled_date
    ),

    CHECK (
        status <> 'completed'
        OR completed_at IS NOT NULL
    ),

    CHECK (
        status = 'completed'
        OR completed_at IS NULL
    ),

    CHECK (
        notes IS NULL
        OR TRIM(notes) <> ''
    )
);

CREATE INDEX IF NOT EXISTS idx_farm_tasks_activity
    ON farm_tasks(farming_activity_id);

CREATE INDEX IF NOT EXISTS idx_farm_tasks_assigned_to
    ON farm_tasks(assigned_to);

CREATE INDEX IF NOT EXISTS idx_farm_tasks_created_by
    ON farm_tasks(created_by);

CREATE INDEX IF NOT EXISTS idx_farm_tasks_status
    ON farm_tasks(status);

CREATE INDEX IF NOT EXISTS idx_farm_tasks_task_type
    ON farm_tasks(task_type);

CREATE INDEX IF NOT EXISTS idx_farm_tasks_scheduled_date
    ON farm_tasks(scheduled_date);

CREATE INDEX IF NOT EXISTS idx_farm_tasks_due_date
    ON farm_tasks(due_date);

CREATE INDEX IF NOT EXISTS idx_farm_tasks_activity_status
    ON farm_tasks(farming_activity_id, status);