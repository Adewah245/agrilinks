CREATE TABLE IF NOT EXISTS conversation_members (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    conversation_id INTEGER NOT NULL,

    user_id INTEGER NOT NULL,

    member_role TEXT NOT NULL DEFAULT 'member',

    joined_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    left_at TIMESTAMP,

    CONSTRAINT fk_conversation_members_conversation
        FOREIGN KEY (conversation_id)
        REFERENCES conversations(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_conversation_members_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    CONSTRAINT unique_conversation_member
        UNIQUE (conversation_id, user_id),

    CONSTRAINT conversation_members_role_check
        CHECK (
            member_role IN (
                'member',
                'admin',
                'owner'
            )
        ),

    CONSTRAINT conversation_members_left_at_check
        CHECK (
            left_at IS NULL
            OR left_at >= joined_at
        )
);


CREATE INDEX IF NOT EXISTS idx_conversation_members_conversation_id
    ON conversation_members(conversation_id);

CREATE INDEX IF NOT EXISTS idx_conversation_members_user_id
    ON conversation_members(user_id);

CREATE INDEX IF NOT EXISTS idx_conversation_members_role
    ON conversation_members(member_role);

CREATE INDEX IF NOT EXISTS idx_conversation_members_joined_at
    ON conversation_members(joined_at);