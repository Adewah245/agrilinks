-- =============================================================
-- 049_platform_revenue.sql
--
-- Ledger for the platform's commission on marketplace sales.
--
-- This is deliberately separate from user wallets: platform money
-- must never be mistaken for, or spent from, a user's balance.
-- gross_amount is the buyer's full payment, amount is the fee, and
-- the seller receives gross_amount - amount.
-- =============================================================

CREATE TABLE IF NOT EXISTS platform_revenue (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    order_id INTEGER NOT NULL,

    reference VARCHAR(120) NOT NULL UNIQUE,

    gross_amount NUMERIC(20,2) NOT NULL,

    amount NUMERIC(20,2) NOT NULL,

    currency VARCHAR(3) NOT NULL DEFAULT 'NGN',

    rate_percent NUMERIC(5,2) NOT NULL,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_platform_revenue_order
        FOREIGN KEY (order_id)
        REFERENCES orders(id)
        ON DELETE RESTRICT,

    CONSTRAINT platform_revenue_reference_nonblank
        CHECK (BTRIM(reference) <> ''),

    CONSTRAINT platform_revenue_gross_amount_check
        CHECK (gross_amount > 0),

    CONSTRAINT platform_revenue_amount_check
        CHECK (amount > 0 AND amount <= gross_amount),

    CONSTRAINT platform_revenue_currency_check
        CHECK (BTRIM(currency) <> ''),

    CONSTRAINT platform_revenue_rate_check
        CHECK (rate_percent >= 0 AND rate_percent <= 100)
);

CREATE INDEX IF NOT EXISTS idx_platform_revenue_created_at
    ON platform_revenue(created_at DESC);

CREATE INDEX IF NOT EXISTS idx_platform_revenue_order
    ON platform_revenue(order_id);
