CREATE TABLE IF NOT EXISTS users (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- =========================================================
    -- Identity
    -- =========================================================
    full_name TEXT NOT NULL,
    phone TEXT UNIQUE NOT NULL,
    email TEXT UNIQUE,

    -- =========================================================
    -- Security
    -- =========================================================
    password_hash TEXT NOT NULL,

    -- =========================================================
    -- Account
    -- role = what the user is on the platform
    -- learner is added by migration 039; learning also remains
    -- available to every authenticated user.
    -- =========================================================
    role TEXT NOT NULL DEFAULT 'farmer',
    account_type TEXT NOT NULL DEFAULT 'individual',

    -- =========================================================
    -- Location
    -- =========================================================
    location TEXT,
    lga TEXT,
    state TEXT,
    country TEXT NOT NULL DEFAULT 'Nigeria',

    -- =========================================================
    -- Organisation / Partner
    -- =========================================================
    organisation_name TEXT,

    -- =========================================================
    -- Profile
    -- A profile photo is optional during registration
    -- =========================================================
    photo_url TEXT,

    -- =========================================================
    -- Timestamps
    -- =========================================================
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- =========================================================
    -- Constraints
    -- =========================================================
    CONSTRAINT users_role_check
        CHECK (
            role IN (
                'farmer',
                'buyer',
                'ministry',
                'organisation'
            )
        ),

    CONSTRAINT users_account_type_check
        CHECK (
            account_type IN (
                'individual',
                'organisation'
            )
        ),

    CONSTRAINT users_phone_nonblank
        CHECK (BTRIM(phone) <> ''),

    CONSTRAINT users_full_name_nonblank
        CHECK (BTRIM(full_name) <> ''),

    CONSTRAINT users_password_hash_nonblank
        CHECK (BTRIM(password_hash) <> '')
);


-- =============================================================
-- Indexes
-- =============================================================

CREATE INDEX IF NOT EXISTS idx_users_phone
ON users(phone);

CREATE INDEX IF NOT EXISTS idx_users_role
ON users(role);

CREATE INDEX IF NOT EXISTS idx_users_state
ON users(state);

CREATE INDEX IF NOT EXISTS idx_users_lga
ON users(lga);

CREATE INDEX IF NOT EXISTS idx_users_account_type
ON users(account_type);
