-- =============================================================
-- 040_payment_profile.sql
--
-- Adds the bank-account and permanent wallet-number fields needed
-- by the wallet transfer upgrade.
--
-- Bank details live in their own table rather than on users so that
-- ordinary/profile queries do not load sensitive financial data.
-- =============================================================

CREATE TABLE IF NOT EXISTS user_bank_accounts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id INTEGER NOT NULL UNIQUE,

    bank_name TEXT NOT NULL,

    bank_code TEXT NOT NULL,

    account_name TEXT NOT NULL,

    account_number TEXT NOT NULL,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_user_bank_accounts_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    CONSTRAINT user_bank_accounts_bank_name_check
        CHECK (BTRIM(bank_name) <> ''),

    CONSTRAINT user_bank_accounts_bank_code_check
        CHECK (BTRIM(bank_code) <> ''),

    CONSTRAINT user_bank_accounts_account_name_check
        CHECK (BTRIM(account_name) <> ''),

    CONSTRAINT user_bank_accounts_account_number_check
        CHECK (BTRIM(account_number) <> '')
);

CREATE INDEX IF NOT EXISTS idx_user_bank_accounts_user_id
    ON user_bank_accounts(user_id);


ALTER TABLE wallets
    ADD COLUMN IF NOT EXISTS wallet_number TEXT;

UPDATE wallets
SET wallet_number =
    'AGW-' ||
    CASE owner_type
        WHEN 'user' THEN 'U'
        WHEN 'organization' THEN 'O'
    END ||
    '-' ||
    LPAD(owner_id::TEXT, 8, '0') ||
    '-' ||
    UPPER(currency)
WHERE wallet_number IS NULL
   OR BTRIM(wallet_number) = '';

CREATE UNIQUE INDEX IF NOT EXISTS idx_wallets_wallet_number_unique
    ON wallets(wallet_number)
    WHERE wallet_number IS NOT NULL;

CREATE OR REPLACE FUNCTION assign_wallet_number()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.wallet_number IS NULL OR BTRIM(NEW.wallet_number) = '' THEN
        NEW.wallet_number :=
            'AGW-' ||
            CASE NEW.owner_type
                WHEN 'user' THEN 'U'
                WHEN 'organization' THEN 'O'
            END ||
            '-' ||
            LPAD(NEW.owner_id::TEXT, 8, '0') ||
            '-' ||
            UPPER(NEW.currency);
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_assign_wallet_number ON wallets;

CREATE TRIGGER trg_assign_wallet_number
    BEFORE INSERT ON wallets
    FOR EACH ROW
    EXECUTE FUNCTION assign_wallet_number();

ALTER TABLE wallets
    ALTER COLUMN wallet_number SET NOT NULL;
