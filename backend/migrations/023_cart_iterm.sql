CREATE TABLE IF NOT EXISTS cart_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    buyer_id INTEGER NOT NULL,

    product_id INTEGER NOT NULL,

    negotiation_id INTEGER,

    quantity DOUBLE PRECISION NOT NULL,

    price_per_unit NUMERIC(20,2) NOT NULL,

    total_price NUMERIC(20,2) NOT NULL,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_cart_items_buyer
        FOREIGN KEY (buyer_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_cart_items_product
        FOREIGN KEY (product_id)
        REFERENCES products(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_cart_items_negotiation
        FOREIGN KEY (negotiation_id)
        REFERENCES negotiations(id)
        ON DELETE SET NULL,

    CONSTRAINT cart_items_quantity_check
        CHECK (quantity > 0),

    CONSTRAINT cart_items_price_check
        CHECK (price_per_unit >= 0),

    CONSTRAINT cart_items_total_price_check
        CHECK (total_price >= 0)
);


CREATE INDEX IF NOT EXISTS idx_cart_items_buyer_id
    ON cart_items(buyer_id);

CREATE INDEX IF NOT EXISTS idx_cart_items_product_id
    ON cart_items(product_id);

CREATE INDEX IF NOT EXISTS idx_cart_items_negotiation_id
    ON cart_items(negotiation_id);

CREATE INDEX IF NOT EXISTS idx_cart_items_buyer_created_at
    ON cart_items(buyer_id, created_at);