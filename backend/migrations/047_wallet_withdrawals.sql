-- =============================================================
-- 047_wallet_withdrawals.sql
--
-- A request to move wallet money to a saved bank account.
--
-- The withdrawal records the payout details used at request time so
-- later bank-account edits cannot change an in-flight payout. The
-- name check result is stored with the request; an empty value means
-- the check has never run, not that it passed.
-- =============================================================

CREATE TABLE IF NOT EXISTS wallet_withdrawals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    wallet_id INTEGER NOT NULL,

    user_id INTEGER NOT NULL,

    reference VARCHAR(100) NOT NULL UNIQUE,

    provider_transfer_id VARCHAR(100) UNIQUE,

    amount NUMERIC(20,2) NOT NULL,

    currency VARCHAR(3) NOT NULL DEFAULT 'NGN',

    bank_name TEXT NOT NULL,

    bank_code TEXT NOT NULL,

    account_name TEXT NOT NULL,

    account_number VARCHAR(10) NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'pending',

    approved_by INTEGER,

    reminded_at TIMESTAMP,

    name_check_status TEXT NOT NULL DEFAULT '',

    name_check_resolved TEXT NOT NULL DEFAULT '',

    name_check_detail TEXT NOT NULL DEFAULT '',

    name_check_at TIMESTAMP,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_wallet_withdrawals_wallet
        FOREIGN KEY (wallet_id)
        REFERENCES wallets(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_wallet_withdrawals_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_wallet_withdrawals_approver
        FOREIGN KEY (approved_by)
        REFERENCES users(id)
        ON DELETE RESTRICT,

    CONSTRAINT wallet_withdrawals_reference_nonblank
        CHECK (BTRIM(reference) <> ''),

    CONSTRAINT wallet_withdrawals_amount_check
        CHECK (amount > 0),

    CONSTRAINT wallet_withdrawals_currency_check
        CHECK (BTRIM(currency) <> ''),

    CONSTRAINT wallet_withdrawals_bank_name_check
        CHECK (BTRIM(bank_name) <> ''),

    CONSTRAINT wallet_withdrawals_bank_code_check
        CHECK (BTRIM(bank_code) <> ''),

    CONSTRAINT wallet_withdrawals_account_name_check
        CHECK (BTRIM(account_name) <> ''),

    CONSTRAINT wallet_withdrawals_account_number_check
        CHECK (account_number ~ '^[0-9]{10}$'),

    CONSTRAINT wallet_withdrawals_status_check
        CHECK (
            status IN (
                'pending',
                'processing',
                'paid',
                'rejected',
                'failed',
                'cancelled',
                'expired'
            )
        ),

    CONSTRAINT wallet_withdrawals_name_check_status_check
        CHECK (
            name_check_status IN (
                '',
                'verified',
                'mismatch',
                'unverified'
            )
        )
);

CREATE INDEX IF NOT EXISTS idx_wallet_withdrawals_status_time
    ON wallet_withdrawals(status, created_at);

CREATE INDEX IF NOT EXISTS idx_wallet_withdrawals_user_time
    ON wallet_withdrawals(user_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_wallet_withdrawals_wallet_time
    ON wallet_withdrawals(wallet_id, created_at DESC);
