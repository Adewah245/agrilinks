CREATE TABLE IF NOT EXISTS farm_assets (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id INTEGER NOT NULL,

    farming_activity_id INTEGER,

    name TEXT NOT NULL,

    asset_type TEXT NOT NULL,

    description TEXT,

    quantity DOUBLE PRECISION NOT NULL DEFAULT 1,

    unit TEXT NOT NULL DEFAULT 'unit',

    status TEXT NOT NULL DEFAULT 'active',

    condition TEXT NOT NULL DEFAULT 'good',

    acquisition_date DATE,

    acquisition_cost NUMERIC(20,2),

    current_value NUMERIC(20,2),

    currency TEXT NOT NULL DEFAULT 'NGN',

    location TEXT,

    notes TEXT,

    metadata JSONB,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    FOREIGN KEY (farming_activity_id)
        REFERENCES farming_activities(id)
        ON DELETE SET NULL,

    CHECK (TRIM(name) <> ''),

    CHECK (
        asset_type IN (
            'tractor',
            'vehicle',
            'generator',
            'water_pump',
            'irrigation_system',
            'farm_building',
            'poultry_house',
            'livestock_shelter',
            'fish_pond',
            'fish_tank',
            'cage',
            'beehive',
            'cold_storage',
            'processing_equipment',
            'machine',
            'tool',
            'other'
        )
    ),

    CHECK (
        description IS NULL
        OR TRIM(description) <> ''
    ),

    CHECK (quantity > 0),

    CHECK (TRIM(unit) <> ''),

    CHECK (
        status IN (
            'active',
            'under_maintenance',
            'inactive',
            'damaged',
            'retired',
            'sold',
            'lost'
        )
    ),

    CHECK (
        condition IN (
            'new',
            'good',
            'fair',
            'poor',
            'damaged'
        )
    ),

    CHECK (
        acquisition_cost IS NULL
        OR acquisition_cost >= 0
    ),

    CHECK (
        current_value IS NULL
        OR current_value >= 0
    ),

    CHECK (
        acquisition_date IS NULL
        OR acquisition_date <= CURRENT_DATE
    ),

    CHECK (TRIM(currency) <> ''),

    CHECK (
        location IS NULL
        OR TRIM(location) <> ''
    ),

    CHECK (
        notes IS NULL
        OR TRIM(notes) <> ''
    )
);

CREATE INDEX IF NOT EXISTS idx_farm_assets_user
    ON farm_assets(user_id);

CREATE INDEX IF NOT EXISTS idx_farm_assets_activity
    ON farm_assets(farming_activity_id);

CREATE INDEX IF NOT EXISTS idx_farm_assets_type
    ON farm_assets(asset_type);

CREATE INDEX IF NOT EXISTS idx_farm_assets_status
    ON farm_assets(status);

CREATE INDEX IF NOT EXISTS idx_farm_assets_condition
    ON farm_assets(condition);

CREATE INDEX IF NOT EXISTS idx_farm_assets_acquisition_date
    ON farm_assets(acquisition_date);