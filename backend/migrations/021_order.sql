-- ============================================================
-- ORDERS
-- ============================================================

CREATE TABLE IF NOT EXISTS orders (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- ========================================================
    -- Buyer
    -- ========================================================
    buyer_id INTEGER NOT NULL,

    -- ========================================================
    -- Order Status
    -- ========================================================
    status TEXT NOT NULL DEFAULT 'pending',

    -- ========================================================
    -- Total Order Amount
    -- ========================================================
    total_amount NUMERIC(20,2) NOT NULL DEFAULT 0,

    -- ========================================================
    -- Timestamps
    -- ========================================================
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,


    -- ========================================================
    -- Buyer Relationship
    -- ========================================================
    CONSTRAINT fk_orders_buyer
        FOREIGN KEY (buyer_id)
        REFERENCES users(id)
        ON DELETE RESTRICT,


    -- ========================================================
    -- Status Validation
    -- ========================================================
    CONSTRAINT orders_status_check
        CHECK (
            status IN (
                'pending',
                'confirmed',
                'processing',
                'ready_for_delivery',
                'shipped',
                'delivered',
                'cancelled'
            )
        ),


    -- ========================================================
    -- Financial Validation
    -- ========================================================
    CONSTRAINT orders_total_amount_check
        CHECK (total_amount >= 0)
);


-- ============================================================
-- ORDER INDEXES
-- ============================================================

CREATE INDEX IF NOT EXISTS idx_orders_buyer_id
    ON orders(buyer_id);

CREATE INDEX IF NOT EXISTS idx_orders_status
    ON orders(status);

CREATE INDEX IF NOT EXISTS idx_orders_created_at
    ON orders(created_at);



-- ============================================================
-- ORDER ITEMS
-- ============================================================
--
-- An order can contain multiple products.
--
-- Example:
--
--   Order #100
--       ├── Product A × 10
--       ├── Product B × 5
--       └── Product C × 2
--
-- Each product becomes a separate order_items row.
-- ============================================================

CREATE TABLE IF NOT EXISTS order_items (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- ========================================================
    -- Parent Order
    -- ========================================================
    order_id INTEGER NOT NULL,

    -- ========================================================
    -- Product
    -- ========================================================
    product_id INTEGER NOT NULL,

    -- ========================================================
    -- Quantity
    --
    -- NUMERIC is used instead of DOUBLE PRECISION because
    -- agricultural products may have fractional quantities.
    -- ========================================================
    quantity NUMERIC(20,6) NOT NULL,

    -- ========================================================
    -- Price captured at time of purchase
    --
    -- We intentionally store the unit price here instead of
    -- relying on the current products.price value.
    --
    -- This preserves historical order accuracy when a seller
    -- changes the product price later.
    -- ========================================================
    unit_price NUMERIC(20,2) NOT NULL,

    total_price NUMERIC(20,2) NOT NULL,

    -- ========================================================
    -- Timestamp
    -- ========================================================
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,


    -- ========================================================
    -- Order Relationship
    -- ========================================================
    CONSTRAINT fk_order_items_order
        FOREIGN KEY (order_id)
        REFERENCES orders(id)
        ON DELETE CASCADE,


    -- ========================================================
    -- Product Relationship
    -- ========================================================
    CONSTRAINT fk_order_items_product
        FOREIGN KEY (product_id)
        REFERENCES products(id)
        ON DELETE RESTRICT,


    -- ========================================================
    -- Quantity Validation
    -- ========================================================
    CONSTRAINT order_items_quantity_check
        CHECK (quantity > 0),


    -- ========================================================
    -- Price Validation
    -- ========================================================
    CONSTRAINT order_items_unit_price_check
        CHECK (unit_price >= 0),

    CONSTRAINT order_items_total_price_check
        CHECK (total_price >= 0)
);


-- ============================================================
-- ORDER ITEM INDEXES
-- ============================================================

CREATE INDEX IF NOT EXISTS idx_order_items_order_id
    ON order_items(order_id);

CREATE INDEX IF NOT EXISTS idx_order_items_product_id
    ON order_items(product_id);

CREATE INDEX IF NOT EXISTS idx_order_items_created_at
    ON order_items(created_at);



-- ============================================================
-- COMPLETE DEFERRED ORDER RELATIONSHIPS
-- ============================================================
--
-- These foreign keys were intentionally omitted from earlier
-- migrations because orders did not exist at that point.
--
-- Now that orders has been created, we can safely establish
-- the relationships.
-- ============================================================


-- ============================================================
-- TRANSACTIONS → ORDERS
-- ============================================================

DO $$
BEGIN

    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_transactions_order'
    ) THEN

        ALTER TABLE transactions
            ADD CONSTRAINT fk_transactions_order
            FOREIGN KEY (order_id)
            REFERENCES orders(id)
            ON DELETE CASCADE;

    END IF;

END
$$;


-- ============================================================
-- PRODUCT REVIEWS → ORDERS
-- ============================================================

DO $$
BEGIN

    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_product_reviews_order'
    ) THEN

        ALTER TABLE product_reviews
            ADD CONSTRAINT fk_product_reviews_order
            FOREIGN KEY (order_id)
            REFERENCES orders(id)
            ON DELETE CASCADE;

    END IF;

END
$$;


-- ============================================================
-- USER REVIEWS → ORDERS
-- ============================================================

DO $$
BEGIN

    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_user_reviews_order'
    ) THEN

        ALTER TABLE user_reviews
            ADD CONSTRAINT fk_user_reviews_order
            FOREIGN KEY (order_id)
            REFERENCES orders(id)
            ON DELETE CASCADE;

    END IF;

END
$$;


