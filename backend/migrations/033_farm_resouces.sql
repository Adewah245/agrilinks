CREATE TABLE IF NOT EXISTS farm_resources (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id INTEGER NOT NULL,

    name TEXT NOT NULL,

    resource_type TEXT NOT NULL,

    description TEXT,

    quantity DOUBLE PRECISION NOT NULL DEFAULT 0,

    unit TEXT NOT NULL,

    minimum_quantity DOUBLE PRECISION,

    location TEXT,

    state_id INTEGER,
    lga_id INTEGER,
    community_id INTEGER,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    FOREIGN KEY (state_id)
        REFERENCES states(id)
        ON DELETE SET NULL,

    FOREIGN KEY (lga_id)
        REFERENCES lgas(id)
        ON DELETE SET NULL,

    FOREIGN KEY (community_id)
        REFERENCES communities(id)
        ON DELETE SET NULL,

    CHECK (TRIM(name) <> ''),

    CHECK (
        resource_type IN (
            'seed',
            'seedling',
            'feed',
            'fertilizer',
            'pesticide',
            'vaccine',
            'medication',
            'fingerling',
            'animal',
            'bee_colony',
            'equipment',
            'tool',
            'fuel',
            'water',
            'packaging',
            'other'
        )
    ),

    CHECK (
        description IS NULL
        OR TRIM(description) <> ''
    ),

    CHECK (quantity >= 0),

    CHECK (TRIM(unit) <> ''),

    CHECK (
        minimum_quantity IS NULL
        OR minimum_quantity >= 0
    )
);

CREATE INDEX IF NOT EXISTS idx_farm_resources_user
    ON farm_resources(user_id);

CREATE INDEX IF NOT EXISTS idx_farm_resources_type
    ON farm_resources(resource_type);

CREATE INDEX IF NOT EXISTS idx_farm_resources_name
    ON farm_resources(name);

CREATE INDEX IF NOT EXISTS idx_farm_resources_state
    ON farm_resources(state_id);

CREATE INDEX IF NOT EXISTS idx_farm_resources_lga
    ON farm_resources(lga_id);

CREATE INDEX IF NOT EXISTS idx_farm_resources_low_stock
    ON farm_resources(user_id, quantity, minimum_quantity);