CREATE TABLE IF NOT EXISTS diagnoses (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id INTEGER NOT NULL,

    farming_type_id INTEGER,

    category TEXT,

    symptoms TEXT,

    result TEXT,

    confidence DOUBLE PRECISION,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_diagnoses_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_diagnoses_farming_type
        FOREIGN KEY (farming_type_id)
        REFERENCES farming_types(id)
        ON DELETE SET NULL,

    CONSTRAINT diagnoses_category_check
        CHECK (
            category IS NULL
            OR BTRIM(category) <> ''
        ),

    CONSTRAINT diagnoses_symptoms_check
        CHECK (
            symptoms IS NULL
            OR BTRIM(symptoms) <> ''
        ),

    CONSTRAINT diagnoses_result_check
        CHECK (
            result IS NULL
            OR BTRIM(result) <> ''
        ),

    CONSTRAINT diagnoses_confidence_check
        CHECK (
            confidence IS NULL
            OR (
                confidence >= 0
                AND confidence <= 1
            )
        )
);

CREATE INDEX IF NOT EXISTS idx_diagnoses_user_id
    ON diagnoses(user_id);

CREATE INDEX IF NOT EXISTS idx_diagnoses_farming_type_id
    ON diagnoses(farming_type_id);

CREATE INDEX IF NOT EXISTS idx_diagnoses_category
    ON diagnoses(category);

CREATE INDEX IF NOT EXISTS idx_diagnoses_created_at
    ON diagnoses(created_at);


-- ============================================
-- DIAGNOSIS MEDIA
--
-- Stores images/files associated with a diagnosis.
-- A diagnosis can have multiple media files.
-- ============================================

CREATE TABLE IF NOT EXISTS diagnosis_media (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    diagnosis_id INTEGER NOT NULL,

    media_type TEXT NOT NULL DEFAULT 'image',

    media_url TEXT NOT NULL,

    image_name TEXT,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_diagnosis_media_diagnosis
        FOREIGN KEY (diagnosis_id)
        REFERENCES diagnoses(id)
        ON DELETE CASCADE,

    CONSTRAINT diagnosis_media_type_check
        CHECK (
            media_type IN (
                'image',
                'video',
                'audio',
                'document'
            )
        ),

    CONSTRAINT diagnosis_media_url_nonblank
        CHECK (BTRIM(media_url) <> ''),

    CONSTRAINT diagnosis_media_image_name_check
        CHECK (
            image_name IS NULL
            OR BTRIM(image_name) <> ''
        )
);

CREATE INDEX IF NOT EXISTS idx_diagnosis_media_diagnosis_id
    ON diagnosis_media(diagnosis_id);

CREATE INDEX IF NOT EXISTS idx_diagnosis_media_type
    ON diagnosis_media(media_type);

CREATE INDEX IF NOT EXISTS idx_diagnosis_media_created_at
    ON diagnosis_media(created_at);