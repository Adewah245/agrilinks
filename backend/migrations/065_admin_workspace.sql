-- Staff permissions are independent of a member's farmer/buyer role.
ALTER TABLE users ADD COLUMN staff_role TEXT NOT NULL DEFAULT ''
    CHECK (staff_role IN ('', 'super_admin', 'customer_care', 'operations_manager'));
ALTER TABLE users ADD COLUMN staff_disabled BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE users ADD COLUMN account_status TEXT NOT NULL DEFAULT 'active'
    CHECK (account_status IN ('active', 'suspended'));
UPDATE users SET staff_role='super_admin' WHERE is_admin;
CREATE INDEX users_staff_role_idx ON users(staff_role) WHERE staff_role <> '';

CREATE TABLE admin_support_tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id),
    order_id INTEGER REFERENCES orders(id),
    subject TEXT NOT NULL CHECK (length(btrim(subject)) BETWEEN 1 AND 200),
    description TEXT NOT NULL CHECK (length(btrim(description)) BETWEEN 1 AND 4000),
    kind TEXT NOT NULL CHECK (kind IN ('support', 'complaint', 'dispute', 'refund')),
    priority TEXT NOT NULL DEFAULT 'normal' CHECK (priority IN ('normal', 'high', 'urgent')),
    status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'in_progress', 'resolved', 'closed')),
    assigned_to INTEGER REFERENCES users(id),
    resolution TEXT NOT NULL DEFAULT '',
    created_by INTEGER NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX admin_tickets_status_idx ON admin_support_tickets(status, updated_at DESC);
CREATE TABLE admin_ticket_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL REFERENCES admin_support_tickets(id),
    actor_id INTEGER NOT NULL REFERENCES users(id),
    status TEXT NOT NULL,
    note TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE admin_moderation_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER REFERENCES users(id),
    product_id INTEGER REFERENCES products(id),
    reason TEXT NOT NULL CHECK (length(btrim(reason)) BETWEEN 1 AND 2000),
    status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'investigating', 'resolved', 'dismissed')),
    resolution TEXT NOT NULL DEFAULT '',
    created_by INTEGER NOT NULL REFERENCES users(id),
    reviewed_by INTEGER REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (num_nonnulls(user_id, product_id) = 1)
);
CREATE INDEX admin_reports_status_idx ON admin_moderation_reports(status, created_at DESC);

CREATE TABLE admin_audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id INTEGER REFERENCES users(id),
    actor_name TEXT NOT NULL,
    actor_role TEXT NOT NULL,
    action TEXT NOT NULL,
    target TEXT NOT NULL,
    before_value JSONB NOT NULL DEFAULT '{}',
    after_value JSONB NOT NULL DEFAULT '{}',
    succeeded BOOLEAN NOT NULL,
    detail TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX admin_audit_time_idx ON admin_audit_logs(created_at DESC);

CREATE FUNCTION reject_admin_history_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Administrative history is append-only';
END;
$$;
CREATE TRIGGER admin_audit_append_only BEFORE UPDATE OR DELETE ON admin_audit_logs
    FOR EACH ROW EXECUTE FUNCTION reject_admin_history_mutation();
CREATE TRIGGER admin_ticket_history_append_only BEFORE UPDATE OR DELETE ON admin_ticket_history
    FOR EACH ROW EXECUTE FUNCTION reject_admin_history_mutation();

