-- ============================================
-- AGRO-SHIELD
-- Migration 012: Reviews & Trust System
-- ============================================
--
-- Defines:
--   1. Product reviews
--   2. User/organization reviews
--   3. Verification / trust badges
--
-- IMPORTANT MIGRATION DEPENDENCY:
--
-- orders is created later in migration 021_order.sql.
--
-- Therefore the order_id columns are created here, but the
-- foreign keys pointing to orders(id) are intentionally added
-- later after the orders table exists.
-- ============================================


-- ============================================
-- PRODUCT REVIEWS
-- ============================================

CREATE TABLE IF NOT EXISTS product_reviews (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    product_id INTEGER NOT NULL,

    reviewer_id INTEGER NOT NULL,

    order_id INTEGER NOT NULL,

    rating INTEGER NOT NULL,

    comment TEXT,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,


    CONSTRAINT fk_product_reviews_product
        FOREIGN KEY (product_id)
        REFERENCES products(id)
        ON DELETE CASCADE,


    CONSTRAINT fk_product_reviews_reviewer
        FOREIGN KEY (reviewer_id)
        REFERENCES users(id)
        ON DELETE CASCADE,


    -- The foreign key to orders(id) is intentionally omitted.
    -- It will be added after migration 021 creates orders.


    CONSTRAINT product_reviews_rating_check
        CHECK (
            rating >= 1
            AND rating <= 5
        ),


    CONSTRAINT product_reviews_comment_check
        CHECK (
            comment IS NULL
            OR BTRIM(comment) <> ''
        ),


    CONSTRAINT unique_product_order_reviewer
        UNIQUE (
            order_id,
            product_id,
            reviewer_id
        )
);


CREATE INDEX IF NOT EXISTS idx_product_reviews_product_id
ON product_reviews(product_id);


CREATE INDEX IF NOT EXISTS idx_product_reviews_reviewer_id
ON product_reviews(reviewer_id);


CREATE INDEX IF NOT EXISTS idx_product_reviews_order_id
ON product_reviews(order_id);


CREATE INDEX IF NOT EXISTS idx_product_reviews_rating
ON product_reviews(rating);


CREATE INDEX IF NOT EXISTS idx_product_reviews_created_at
ON product_reviews(created_at);



-- ============================================
-- USER / ORGANIZATION REVIEWS
-- ============================================

CREATE TABLE IF NOT EXISTS user_reviews (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    reviewed_type TEXT NOT NULL,

    reviewed_id INTEGER NOT NULL,

    reviewer_id INTEGER NOT NULL,

    order_id INTEGER NOT NULL,

    rating INTEGER NOT NULL,

    comment TEXT,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,


    CONSTRAINT fk_user_reviews_reviewer
        FOREIGN KEY (reviewer_id)
        REFERENCES users(id)
        ON DELETE CASCADE,


    -- The foreign key to orders(id) is intentionally omitted.
    -- It will be added after migration 021 creates orders.


    CONSTRAINT user_reviews_reviewed_type_check
        CHECK (
            reviewed_type IN (
                'user',
                'organization'
            )
        ),


    CONSTRAINT user_reviews_reviewed_id_check
        CHECK (
            reviewed_id > 0
        ),


    CONSTRAINT user_reviews_rating_check
        CHECK (
            rating >= 1
            AND rating <= 5
        ),


    CONSTRAINT user_reviews_comment_check
        CHECK (
            comment IS NULL
            OR BTRIM(comment) <> ''
        ),


    CONSTRAINT unique_reviewed_order_reviewer
        UNIQUE (
            order_id,
            reviewer_id,
            reviewed_type,
            reviewed_id
        )
);


CREATE INDEX IF NOT EXISTS idx_user_reviews_reviewed
ON user_reviews(reviewed_type, reviewed_id);


CREATE INDEX IF NOT EXISTS idx_user_reviews_reviewer_id
ON user_reviews(reviewer_id);


CREATE INDEX IF NOT EXISTS idx_user_reviews_order_id
ON user_reviews(order_id);


CREATE INDEX IF NOT EXISTS idx_user_reviews_rating
ON user_reviews(rating);


CREATE INDEX IF NOT EXISTS idx_user_reviews_created_at
ON user_reviews(created_at);



-- ============================================
-- VERIFICATION / TRUST BADGES
-- ============================================

CREATE TABLE IF NOT EXISTS verification_badges (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    owner_type TEXT NOT NULL,

    owner_id INTEGER NOT NULL,

    badge_type TEXT NOT NULL,

    issued_by INTEGER,

    description TEXT,

    issued_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    expires_at TIMESTAMP,

    active BOOLEAN NOT NULL DEFAULT TRUE,


    CONSTRAINT fk_verification_badges_issuer
        FOREIGN KEY (issued_by)
        REFERENCES users(id)
        ON DELETE SET NULL,


    CONSTRAINT verification_badges_owner_type_check
        CHECK (
            owner_type IN (
                'user',
                'organization'
            )
        ),


    CONSTRAINT verification_badges_owner_id_check
        CHECK (
            owner_id > 0
        ),


    CONSTRAINT verification_badges_type_check
        CHECK (
            badge_type IN (
                'verified_farmer',
                'verified_organization',
                'government_partner',
                'trusted_seller'
            )
        ),


    CONSTRAINT verification_badges_description_check
        CHECK (
            description IS NULL
            OR BTRIM(description) <> ''
        ),


    CONSTRAINT verification_badges_expiry_check
        CHECK (
            expires_at IS NULL
            OR expires_at >= issued_at
        )
);


CREATE INDEX IF NOT EXISTS idx_verification_badges_owner
ON verification_badges(owner_type, owner_id);


CREATE INDEX IF NOT EXISTS idx_verification_badges_type
ON verification_badges(badge_type);


CREATE INDEX IF NOT EXISTS idx_verification_badges_active
ON verification_badges(active);


CREATE INDEX IF NOT EXISTS idx_verification_badges_expires_at
ON verification_badges(expires_at);


CREATE INDEX IF NOT EXISTS idx_verification_badges_issuer
ON verification_badges(issued_by);


-- Prevent duplicate active badges for the same owner.
CREATE UNIQUE INDEX IF NOT EXISTS uq_active_verification_badge
ON verification_badges(owner_type, owner_id, badge_type)
WHERE active = TRUE;
