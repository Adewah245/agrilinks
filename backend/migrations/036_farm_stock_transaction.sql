CREATE TABLE IF NOT EXISTS farm_stock_transactions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    stock_id INTEGER NOT NULL,

    farming_activity_id INTEGER NOT NULL,

    recorded_by INTEGER NOT NULL,

    transaction_type TEXT NOT NULL,

    quantity DOUBLE PRECISION NOT NULL,

    transaction_date DATE NOT NULL DEFAULT CURRENT_DATE,

    reference TEXT,

    notes TEXT,

    metadata JSONB,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    FOREIGN KEY (stock_id)
        REFERENCES farm_stock(id)
        ON DELETE CASCADE,

    FOREIGN KEY (farming_activity_id)
        REFERENCES farming_activities(id)
        ON DELETE CASCADE,

    FOREIGN KEY (recorded_by)
        REFERENCES users(id)
        ON DELETE RESTRICT,

    CHECK (
        transaction_type IN (
            'production',
            'purchase',
            'received',
            'sale',
            'consumption',
            'loss',
            'damage',
            'expired',
            'transfer_in',
            'transfer_out',
            'adjustment'
        )
    ),

    CHECK (quantity > 0),

    CHECK (
        reference IS NULL
        OR TRIM(reference) <> ''
    ),

    CHECK (
        notes IS NULL
        OR TRIM(notes) <> ''
    )
);

CREATE INDEX IF NOT EXISTS idx_farm_stock_transactions_stock
    ON farm_stock_transactions(stock_id);

CREATE INDEX IF NOT EXISTS idx_farm_stock_transactions_activity
    ON farm_stock_transactions(farming_activity_id);

CREATE INDEX IF NOT EXISTS idx_farm_stock_transactions_recorded_by
    ON farm_stock_transactions(recorded_by);

CREATE INDEX IF NOT EXISTS idx_farm_stock_transactions_type
    ON farm_stock_transactions(transaction_type);

CREATE INDEX IF NOT EXISTS idx_farm_stock_transactions_date
    ON farm_stock_transactions(transaction_date);

CREATE INDEX IF NOT EXISTS idx_farm_stock_transactions_stock_date
    ON farm_stock_transactions(stock_id, transaction_date);

CREATE INDEX IF NOT EXISTS idx_farm_stock_transactions_activity_date
    ON farm_stock_transactions(
        farming_activity_id,
        transaction_date
    );