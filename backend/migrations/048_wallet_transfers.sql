-- =============================================================
-- 048_wallet_transfers.sql
--
-- Wallet-to-wallet transfers. The sender's money is reserved when
-- the transfer is requested and the recipient is credited only
-- after approval, so a mistaken or fraudulent transfer can be
-- reversed while the funds are still held by the platform.
-- =============================================================

CREATE TABLE IF NOT EXISTS wallet_transfers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    sender_wallet_id INTEGER NOT NULL,

    sender_id INTEGER NOT NULL,

    recipient_wallet_id INTEGER NOT NULL,

    recipient_id INTEGER NOT NULL,

    recipient_phone TEXT NOT NULL,

    reference VARCHAR(100) NOT NULL UNIQUE,

    amount NUMERIC(20,2) NOT NULL,

    currency VARCHAR(3) NOT NULL DEFAULT 'NGN',

    note TEXT NOT NULL DEFAULT '',

    status VARCHAR(20) NOT NULL DEFAULT 'pending',

    approved_by INTEGER,

    reminded_at TIMESTAMP,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_wallet_transfers_sender_wallet
        FOREIGN KEY (sender_wallet_id)
        REFERENCES wallets(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_wallet_transfers_sender
        FOREIGN KEY (sender_id)
        REFERENCES users(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_wallet_transfers_recipient_wallet
        FOREIGN KEY (recipient_wallet_id)
        REFERENCES wallets(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_wallet_transfers_recipient
        FOREIGN KEY (recipient_id)
        REFERENCES users(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_wallet_transfers_approver
        FOREIGN KEY (approved_by)
        REFERENCES users(id)
        ON DELETE RESTRICT,

    CONSTRAINT wallet_transfers_reference_nonblank
        CHECK (BTRIM(reference) <> ''),

    CONSTRAINT wallet_transfers_amount_check
        CHECK (amount > 0),

    CONSTRAINT wallet_transfers_currency_check
        CHECK (BTRIM(currency) <> ''),

    CONSTRAINT wallet_transfers_recipient_phone_check
        CHECK (BTRIM(recipient_phone) <> ''),

    CONSTRAINT wallet_transfers_not_self
        CHECK (sender_id <> recipient_id),

    CONSTRAINT wallet_transfers_status_check
        CHECK (
            status IN (
                'pending',
                'completed',
                'rejected',
                'cancelled',
                'expired'
            )
        )
);

CREATE INDEX IF NOT EXISTS idx_wallet_transfers_status_time
    ON wallet_transfers(status, created_at);

CREATE INDEX IF NOT EXISTS idx_wallet_transfers_sender_time
    ON wallet_transfers(sender_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_wallet_transfers_recipient_time
    ON wallet_transfers(recipient_id, created_at DESC);
