-- 009_negotiation.sql
--
-- Product Negotiations
--
-- Negotiation flow:
--
--   Buyer
--      │
--      ▼
--   Product
--      │
--      ▼
--   Negotiation
--      │
--      ├── Message
--      ├── Offer
--      ├── Counter Offer
--      └── Offer History
--      │
--      ▼
--   Accepted Negotiation
--      │
--      ▼
--     Order
--
-- IMPORTANT:
--
-- The seller/owner is NOT duplicated inside negotiations.
--
-- The seller is determined from:
--
--   products.owner_type
--   products.owner_id
--
-- Therefore:
--
--   products
--      ├── owner_type = user
--      │       └── owner_id → users.id
--      │
--      └── owner_type = organization
--              └── owner_id → organizations.id
--
-- The application/service layer is responsible for validating
-- polymorphic ownership.
--
-- Negotiation messages and offers are NEVER overwritten.
-- Every offer remains part of the negotiation history.
-- =============================================================


-- =============================================================
-- 1. NEGOTIATIONS
-- =============================================================

CREATE TABLE IF NOT EXISTS negotiations (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- =========================================================
    -- PRODUCT
    -- =========================================================

    product_id INTEGER NOT NULL,

    -- =========================================================
    -- BUYER
    -- =========================================================

    buyer_id INTEGER NOT NULL,

    -- =========================================================
    -- QUANTITY
    --
    -- The unit comes from products.unit.
    -- We deliberately do not duplicate the product unit here.
    -- =========================================================

    quantity DOUBLE PRECISION NOT NULL,

    -- =========================================================
    -- OFFER PRICING
    --
    -- NUMERIC is used instead of DOUBLE PRECISION because these
    -- are financial values.
    -- =========================================================

    initial_offer_price NUMERIC(20,2) NOT NULL,

    current_offer_price NUMERIC(20,2) NOT NULL,

    -- =========================================================
    -- NEGOTIATION ROUNDS
    --
    -- round_count represents completed offer rounds.
    --
    -- max_rounds allows Agro-Shield to configure the maximum
    -- number of negotiation rounds for this negotiation.
    -- =========================================================

    round_count INTEGER NOT NULL DEFAULT 0,

    max_rounds INTEGER NOT NULL DEFAULT 5,

    -- =========================================================
    -- STATUS
    -- =========================================================

    status TEXT NOT NULL DEFAULT 'open',

    -- =========================================================
    -- EXPIRATION
    --
    -- Every negotiation must have an expiry time.
    -- =========================================================

    expires_at TIMESTAMP NOT NULL,

    -- =========================================================
    -- FINAL STATE TIMESTAMPS
    -- =========================================================

    accepted_at TIMESTAMP,

    closed_at TIMESTAMP,

    -- =========================================================
    -- AUDIT TIMESTAMPS
    -- =========================================================

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,


    -- =========================================================
    -- FOREIGN KEYS
    -- =========================================================

    CONSTRAINT fk_negotiations_product
        FOREIGN KEY (product_id)
        REFERENCES products(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_negotiations_buyer
        FOREIGN KEY (buyer_id)
        REFERENCES users(id)
        ON DELETE RESTRICT,


    -- =========================================================
    -- VALIDATION
    -- =========================================================

    CONSTRAINT negotiations_quantity_check
        CHECK (
            quantity > 0
        ),

    CONSTRAINT negotiations_initial_offer_check
        CHECK (
            initial_offer_price >= 0
        ),

    CONSTRAINT negotiations_current_offer_check
        CHECK (
            current_offer_price >= 0
        ),

    CONSTRAINT negotiations_round_count_check
        CHECK (
            round_count >= 0
            AND round_count <= max_rounds
        ),

    CONSTRAINT negotiations_max_rounds_check
        CHECK (
            max_rounds > 0
        ),

    CONSTRAINT negotiations_status_check
        CHECK (
            status IN (
                'open',
                'accepted',
                'rejected',
                'expired',
                'closed'
            )
        ),

    CONSTRAINT negotiations_expiry_check
        CHECK (
            expires_at > created_at
        ),

    -- =========================================================
    -- ACCEPTED STATE
    --
    -- Accepted negotiation must have accepted_at.
    -- Non-accepted negotiation must not have accepted_at.
    -- =========================================================

    CONSTRAINT negotiations_accepted_at_check
        CHECK (
            (
                status = 'accepted'
                AND accepted_at IS NOT NULL
            )
            OR
            (
                status <> 'accepted'
                AND accepted_at IS NULL
            )
        ),

    -- =========================================================
    -- CLOSED STATE
    --
    -- Rejected, expired and closed negotiations must have
    -- closed_at.
    --
    -- Open and accepted negotiations remain active/finalized
    -- without closed_at.
    -- =========================================================

    CONSTRAINT negotiations_closed_at_check
        CHECK (
            (
                status IN (
                    'rejected',
                    'expired',
                    'closed'
                )
                AND closed_at IS NOT NULL
            )
            OR
            (
                status IN (
                    'open',
                    'accepted'
                )
                AND closed_at IS NULL
            )
        ),

    -- =========================================================
    -- TIMESTAMP ORDER
    -- =========================================================

    CONSTRAINT negotiations_accepted_time_check
        CHECK (
            accepted_at IS NULL
            OR accepted_at >= created_at
        ),

    CONSTRAINT negotiations_closed_time_check
        CHECK (
            closed_at IS NULL
            OR closed_at >= created_at
        )
);


-- =============================================================
-- 2. NEGOTIATION INDEXES
-- =============================================================

CREATE INDEX IF NOT EXISTS idx_negotiations_product_id
    ON negotiations(product_id);

CREATE INDEX IF NOT EXISTS idx_negotiations_buyer_id
    ON negotiations(buyer_id);

CREATE INDEX IF NOT EXISTS idx_negotiations_status
    ON negotiations(status);

CREATE INDEX IF NOT EXISTS idx_negotiations_expires_at
    ON negotiations(expires_at);

CREATE INDEX IF NOT EXISTS idx_negotiations_created_at
    ON negotiations(created_at);

CREATE INDEX IF NOT EXISTS idx_negotiations_buyer_product
    ON negotiations(buyer_id, product_id);


-- =============================================================
-- 3. NEGOTIATION MESSAGES
--
-- Every negotiation message is permanently stored.
--
-- Example:
--
-- Buyer:
--   "Can you sell 100kg?"
--
-- Seller:
--   Offer: ₦150,000
--
-- Buyer:
--   Offer: ₦135,000
--
-- Seller:
--   Offer: ₦145,000
--
-- None of these records are overwritten.
-- =============================================================

CREATE TABLE IF NOT EXISTS negotiation_messages (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- =========================================================
    -- NEGOTIATION
    -- =========================================================

    negotiation_id INTEGER NOT NULL,

    -- =========================================================
    -- SENDER
    -- =========================================================

    sender_id INTEGER NOT NULL,

    -- =========================================================
    -- MESSAGE TYPE
    -- =========================================================

    message_type TEXT NOT NULL DEFAULT 'message',

    -- =========================================================
    -- MESSAGE CONTENT
    --
    -- Normal message:
    --   required
    --
    -- Offer:
    --   optional
    -- =========================================================

    message TEXT,

    -- =========================================================
    -- OFFER PRICE
    --
    -- NULL for ordinary messages.
    -- Required for offers.
    -- =========================================================

    offer_price NUMERIC(20,2),

    -- =========================================================
    -- OFFER STATUS
    -- =========================================================

    offer_status TEXT NOT NULL DEFAULT 'none',

    -- =========================================================
    -- TIMESTAMP
    -- =========================================================

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,


    -- =========================================================
    -- FOREIGN KEYS
    -- =========================================================

    CONSTRAINT fk_negotiation_messages_negotiation
        FOREIGN KEY (negotiation_id)
        REFERENCES negotiations(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_negotiation_messages_sender
        FOREIGN KEY (sender_id)
        REFERENCES users(id)
        ON DELETE RESTRICT,


    -- =========================================================
    -- MESSAGE TYPE
    -- =========================================================

    CONSTRAINT negotiation_messages_type_check
        CHECK (
            message_type IN (
                'message',
                'offer'
            )
        ),


    -- =========================================================
    -- OFFER STATUS
    -- =========================================================

    CONSTRAINT negotiation_messages_offer_status_check
        CHECK (
            offer_status IN (
                'none',
                'pending',
                'accepted',
                'rejected'
            )
        ),


    -- =========================================================
    -- MESSAGE / OFFER VALIDATION
    --
    -- NORMAL MESSAGE:
    --   message required
    --   offer_price must be NULL
    --   offer_status must be none
    --
    -- OFFER:
    --   offer_price required
    --   offer_price >= 0
    --   offer_status cannot be none
    --
    -- An offer may optionally contain explanatory text.
    -- =========================================================

    CONSTRAINT negotiation_messages_content_check
        CHECK (
            (
                message_type = 'message'
                AND message IS NOT NULL
                AND BTRIM(message) <> ''
                AND offer_price IS NULL
                AND offer_status = 'none'
            )
            OR
            (
                message_type = 'offer'
                AND offer_price IS NOT NULL
                AND offer_price >= 0
                AND offer_status <> 'none'
            )
        )
);


-- =============================================================
-- 4. NEGOTIATION MESSAGE INDEXES
-- =============================================================

CREATE INDEX IF NOT EXISTS idx_negotiation_messages_negotiation_id
    ON negotiation_messages(negotiation_id);

CREATE INDEX IF NOT EXISTS idx_negotiation_messages_sender_id
    ON negotiation_messages(sender_id);

CREATE INDEX IF NOT EXISTS idx_negotiation_messages_created_at
    ON negotiation_messages(created_at);

CREATE INDEX IF NOT EXISTS idx_negotiation_messages_offer_status
    ON negotiation_messages(offer_status);

CREATE INDEX IF NOT EXISTS idx_negotiation_messages_type
    ON negotiation_messages(message_type);


