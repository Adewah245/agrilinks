-- =============================================================
-- 041_otp_codes.sql
--
-- Stores hashed one-time passcodes for withdrawals, transfers, and
-- password resets. Plaintext codes are delivered through the configured
-- channel and are never stored in the database.
-- =============================================================

CREATE TABLE IF NOT EXISTS otp_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id INTEGER NOT NULL,

    phone TEXT NOT NULL,

    purpose TEXT NOT NULL,

    code_hash TEXT NOT NULL,

    attempts INTEGER NOT NULL DEFAULT 0,

    expires_at TIMESTAMP NOT NULL,

    consumed_at TIMESTAMP,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_otp_codes_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    CONSTRAINT otp_codes_phone_nonblank
        CHECK (BTRIM(phone) <> ''),

    CONSTRAINT otp_codes_purpose_check
        CHECK (
            purpose IN (
                'withdrawal',
                'transfer',
                'password_reset'
            )
        ),

    CONSTRAINT otp_codes_hash_nonblank
        CHECK (BTRIM(code_hash) <> ''),

    CONSTRAINT otp_codes_attempts_check
        CHECK (attempts >= 0),

    CONSTRAINT otp_codes_expiry_check
        CHECK (expires_at > created_at)
);

CREATE INDEX IF NOT EXISTS idx_otp_codes_user_purpose
    ON otp_codes(user_id, purpose, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_otp_codes_expiry
    ON otp_codes(expires_at);
