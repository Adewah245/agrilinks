-- =============================================================
-- 050_webhook_events.sql
--
-- Durable record of payment-provider webhook deliveries.
--
-- A provider may deliver the same event more than once. The unique
-- key includes the provider so one vendor's transaction ids cannot
-- hide another vendor's delivery, and processed_at records whether
-- the application has already acted on the event.
-- =============================================================

CREATE TABLE IF NOT EXISTS webhook_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    provider VARCHAR(30) NOT NULL DEFAULT 'flutterwave',

    transaction_id VARCHAR(100) NOT NULL,

    event VARCHAR(100) NOT NULL,

    payload JSONB NOT NULL,

    processed_at TIMESTAMP,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT webhook_events_provider_nonblank
        CHECK (BTRIM(provider) <> ''),

    CONSTRAINT webhook_events_transaction_nonblank
        CHECK (BTRIM(transaction_id) <> ''),

    CONSTRAINT webhook_events_event_nonblank
        CHECK (BTRIM(event) <> ''),

    CONSTRAINT webhook_events_provider_transaction_event_unique
        UNIQUE (provider, transaction_id, event)
);

CREATE INDEX IF NOT EXISTS idx_webhook_events_processed_at
    ON webhook_events(processed_at, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_webhook_events_transaction
    ON webhook_events(transaction_id);
