-- =============================================================
-- 056_delivery_partner_members.sql
--
-- Delivery partners are businesses, while the people who operate
-- them are normal Agro-Shield users. Keeping membership in its own
-- table lets one partner have an owner, managers, and drivers without
-- duplicating partner details or adding a logistics-only login table.
-- =============================================================

CREATE TABLE IF NOT EXISTS delivery_partner_members (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    delivery_partner_id INTEGER NOT NULL,

    user_id INTEGER NOT NULL,

    member_role TEXT NOT NULL DEFAULT 'driver',

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_delivery_partner_members_partner
        FOREIGN KEY (delivery_partner_id)
        REFERENCES delivery_partners(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_delivery_partner_members_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    CONSTRAINT unique_delivery_partner_member
        UNIQUE (delivery_partner_id, user_id),

    CONSTRAINT delivery_partner_member_role_check
        CHECK (member_role IN ('owner', 'manager', 'driver'))
);


CREATE INDEX IF NOT EXISTS idx_delivery_partner_members_partner_id
    ON delivery_partner_members(delivery_partner_id);

CREATE INDEX IF NOT EXISTS idx_delivery_partner_members_user_id
    ON delivery_partner_members(user_id);
