-- ============================================================
-- 027_farming_activities.sql
-- General Farming Activities / Production Cycles
-- Supports all farming types
-- ============================================================

CREATE TABLE IF NOT EXISTS farming_activities (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id INTEGER NOT NULL,

    farming_type_id INTEGER NOT NULL,

    name TEXT NOT NULL,

    description TEXT,

    start_date DATE NOT NULL,

    expected_maturity_date DATE,

    actual_completion_date DATE,

    current_stage TEXT,

    status TEXT NOT NULL DEFAULT 'active',

    quantity DOUBLE PRECISION,

    unit TEXT,

    location TEXT,

    state_id INTEGER,

    lga_id INTEGER,

    community_id INTEGER,

    notes TEXT,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_farming_activities_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_farming_activities_farming_type
        FOREIGN KEY (farming_type_id)
        REFERENCES farming_types(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_farming_activities_state
        FOREIGN KEY (state_id)
        REFERENCES states(id)
        ON DELETE SET NULL,

    CONSTRAINT fk_farming_activities_lga
        FOREIGN KEY (lga_id)
        REFERENCES lgas(id)
        ON DELETE SET NULL,

    CONSTRAINT fk_farming_activities_community
        FOREIGN KEY (community_id)
        REFERENCES communities(id)
        ON DELETE SET NULL,

    CONSTRAINT farming_activities_name_nonblank
        CHECK (BTRIM(name) <> ''),

    CONSTRAINT farming_activities_description_check
        CHECK (
            description IS NULL
            OR BTRIM(description) <> ''
        ),

    CONSTRAINT farming_activities_stage_check
        CHECK (
            current_stage IS NULL
            OR BTRIM(current_stage) <> ''
        ),

    CONSTRAINT farming_activities_status_check
        CHECK (
            status IN (
                'planned',
                'active',
                'completed',
                'cancelled',
                'paused'
            )
        ),

    CONSTRAINT farming_activities_quantity_check
        CHECK (
            quantity IS NULL
            OR quantity > 0
        ),

    CONSTRAINT farming_activities_unit_check
        CHECK (
            quantity IS NULL
            OR (
                unit IS NOT NULL
                AND BTRIM(unit) <> ''
            )
        ),

    CONSTRAINT farming_activities_maturity_date_check
        CHECK (
            expected_maturity_date IS NULL
            OR expected_maturity_date >= start_date
        ),

    CONSTRAINT farming_activities_completion_date_check
        CHECK (
            actual_completion_date IS NULL
            OR actual_completion_date >= start_date
        ),

    CONSTRAINT farming_activities_notes_check
        CHECK (
            notes IS NULL
            OR BTRIM(notes) <> ''
        )
);


CREATE INDEX IF NOT EXISTS idx_farming_activities_user_id
    ON farming_activities(user_id);

CREATE INDEX IF NOT EXISTS idx_farming_activities_farming_type_id
    ON farming_activities(farming_type_id);

CREATE INDEX IF NOT EXISTS idx_farming_activities_status
    ON farming_activities(status);

CREATE INDEX IF NOT EXISTS idx_farming_activities_start_date
    ON farming_activities(start_date);

CREATE INDEX IF NOT EXISTS idx_farming_activities_expected_maturity
    ON farming_activities(expected_maturity_date);

CREATE INDEX IF NOT EXISTS idx_farming_activities_state_id
    ON farming_activities(state_id);

CREATE INDEX IF NOT EXISTS idx_farming_activities_lga_id
    ON farming_activities(lga_id);

CREATE INDEX IF NOT EXISTS idx_farming_activities_community_id
    ON farming_activities(community_id);

CREATE INDEX IF NOT EXISTS idx_farming_activities_user_status
    ON farming_activities(user_id, status);