-- ============================================
-- PRODUCT REVIEWS
-- ============================================

CREATE TABLE IF NOT EXISTS product_reviews (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,


    product_id INTEGER NOT NULL,


    reviewer_id INTEGER NOT NULL,


    order_id INTEGER NOT NULL,


    rating INTEGER NOT NULL,


    comment TEXT,


    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,


    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,


    CONSTRAINT fk_product_review_product
        FOREIGN KEY (product_id)
        REFERENCES products(id)
        ON DELETE CASCADE,


    CONSTRAINT fk_product_review_user
        FOREIGN KEY (reviewer_id)
        REFERENCES users(id)
        ON DELETE CASCADE,


    CONSTRAINT fk_product_review_order
        FOREIGN KEY (order_id)
        REFERENCES orders(id)
        ON DELETE CASCADE,


    CONSTRAINT product_review_rating_check
        CHECK (
            rating >= 1
            AND rating <= 5
        ),


    CONSTRAINT unique_product_order_review
        UNIQUE(order_id, reviewer_id)
);



CREATE INDEX IF NOT EXISTS idx_product_reviews_product
ON product_reviews(product_id);



CREATE INDEX IF NOT EXISTS idx_product_reviews_rating
ON product_reviews(rating);



-- ============================================
-- USER / FARMER REVIEWS
-- ============================================

CREATE TABLE IF NOT EXISTS user_reviews (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,


    reviewed_user_id INTEGER NOT NULL,


    reviewer_id INTEGER NOT NULL,


    order_id INTEGER NOT NULL,


    rating INTEGER NOT NULL,


    comment TEXT,


    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,


    CONSTRAINT fk_user_review_target
        FOREIGN KEY (reviewed_user_id)
        REFERENCES users(id)
        ON DELETE CASCADE,


    CONSTRAINT fk_user_review_author
        FOREIGN KEY (reviewer_id)
        REFERENCES users(id)
        ON DELETE CASCADE,


    CONSTRAINT fk_user_review_order
        FOREIGN KEY (order_id)
        REFERENCES orders(id)
        ON DELETE CASCADE,


    CONSTRAINT user_review_rating_check
        CHECK (
            rating >= 1
            AND rating <= 5
        ),


    CONSTRAINT unique_user_order_review
        UNIQUE(order_id, reviewer_id, reviewed_user_id)
);



CREATE INDEX IF NOT EXISTS idx_user_reviews_target
ON user_reviews(reviewed_user_id);



-- ============================================
-- VERIFIED BADGES
-- ============================================

CREATE TABLE IF NOT EXISTS verification_badges (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,


    user_id INTEGER NOT NULL,


    badge_type TEXT NOT NULL,


    issued_by INTEGER,


    description TEXT,


    issued_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,


    expires_at TIMESTAMP,


    active BOOLEAN NOT NULL DEFAULT TRUE,


    CONSTRAINT fk_badge_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE,


    CONSTRAINT fk_badge_issuer
        FOREIGN KEY (issued_by)
        REFERENCES users(id)
        ON DELETE SET NULL,


    CONSTRAINT badge_type_check
        CHECK (
            badge_type IN (
                'verified_farmer',
                'verified_organization',
                'government_partner',
                'trusted_seller'
            )
        )
);



CREATE INDEX IF NOT EXISTS idx_badges_user
ON verification_badges(user_id);



CREATE INDEX IF NOT EXISTS idx_badges_type
ON verification_badges(badge_type);