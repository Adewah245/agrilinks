-- ============================================
-- USER FARMING TYPES
-- ============================================
-- Represents the relationship between a user
-- and a farming type.
--
-- IMPORTANT:
-- This is NOT a user role.
--
-- A user can have multiple farming types:
--
-- Crop Farming  -> confirmed
-- Poultry       -> learning
-- Fisheries     -> interested
--
-- This table is also where the platform records
-- when a user becomes a confirmed farmer of a
-- particular farming type.
-- ============================================

CREATE TABLE IF NOT EXISTS user_farming_types (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id INTEGER NOT NULL,

    farming_type_id INTEGER NOT NULL,

    status TEXT NOT NULL DEFAULT 'interested',

    source TEXT NOT NULL DEFAULT 'user_selection',

    confirmed_at TIMESTAMP,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,


    CONSTRAINT fk_user_farming_types_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE,


    CONSTRAINT fk_user_farming_types_farming_type
        FOREIGN KEY (farming_type_id)
        REFERENCES farming_types(id)
        ON DELETE CASCADE,


    CONSTRAINT user_farming_types_status_check
        CHECK (
            status IN (
                'interested',
                'learning',
                'preparing',
                'confirmed'
            )
        ),


    CONSTRAINT user_farming_types_source_check
        CHECK (
            source IN (
                'user_selection',
                'learning_journey',
                'admin_confirmation'
            )
        ),


    CONSTRAINT user_farming_types_confirmation_check
        CHECK (
            (
                status = 'confirmed'
                AND confirmed_at IS NOT NULL
            )
            OR
            (
                status <> 'confirmed'
            )
        ),


    CONSTRAINT unique_user_farming_type
        UNIQUE (
            user_id,
            farming_type_id
        )
);


CREATE INDEX IF NOT EXISTS idx_user_farming_types_user_id
ON user_farming_types(user_id);


CREATE INDEX IF NOT EXISTS idx_user_farming_types_farming_type_id
ON user_farming_types(farming_type_id);


CREATE INDEX IF NOT EXISTS idx_user_farming_types_status
ON user_farming_types(status);


CREATE INDEX IF NOT EXISTS idx_user_farming_types_user_status
ON user_farming_types(user_id, status);



-- ============================================
-- AI LEARNING JOURNEYS
-- ============================================
-- One journey represents a user's learning/
-- preparation journey for one farming type.
--
-- A user can have multiple journeys for
-- different farming types.
-- ============================================

CREATE TABLE IF NOT EXISTS learning_journeys (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id INTEGER NOT NULL,

    farming_type_id INTEGER NOT NULL,

    user_farming_type_id INTEGER NOT NULL,

    status TEXT NOT NULL DEFAULT 'active',

    experience_level TEXT NOT NULL DEFAULT 'beginner',

    goal TEXT,

    current_stage TEXT NOT NULL DEFAULT 'interest',

    readiness_score INTEGER NOT NULL DEFAULT 0,

    started_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    last_activity_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    completed_at TIMESTAMP,

    confirmed_at TIMESTAMP,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,


    CONSTRAINT fk_learning_journeys_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE,


    CONSTRAINT fk_learning_journeys_farming_type
        FOREIGN KEY (farming_type_id)
        REFERENCES farming_types(id)
        ON DELETE CASCADE,


    CONSTRAINT fk_learning_journeys_user_farming_type
        FOREIGN KEY (user_farming_type_id)
        REFERENCES user_farming_types(id)
        ON DELETE CASCADE,


    CONSTRAINT learning_journeys_status_check
        CHECK (
            status IN (
                'active',
                'paused',
                'completed',
                'abandoned'
            )
        ),


    CONSTRAINT learning_journeys_experience_level_check
        CHECK (
            experience_level IN (
                'beginner',
                'some_experience',
                'experienced'
            )
        ),


    CONSTRAINT learning_journeys_stage_check
        CHECK (
            current_stage IN (
                'interest',
                'learning',
                'preparation',
                'readiness',
                'confirmation',
                'confirmed'
            )
        ),


    CONSTRAINT learning_journeys_goal_check
        CHECK (
            goal IS NULL
            OR BTRIM(goal) <> ''
        ),


    CONSTRAINT learning_journeys_readiness_score_check
        CHECK (
            readiness_score >= 0
            AND readiness_score <= 100
        ),


    CONSTRAINT learning_journeys_completed_at_check
        CHECK (
            completed_at IS NULL
            OR completed_at >= started_at
        ),


    CONSTRAINT learning_journeys_confirmed_at_check
        CHECK (
            confirmed_at IS NULL
            OR confirmed_at >= started_at
        )
);


CREATE INDEX IF NOT EXISTS idx_learning_journeys_user_id
ON learning_journeys(user_id);


CREATE INDEX IF NOT EXISTS idx_learning_journeys_farming_type_id
ON learning_journeys(farming_type_id);


CREATE INDEX IF NOT EXISTS idx_learning_journeys_user_farming_type
ON learning_journeys(user_farming_type_id);


CREATE INDEX IF NOT EXISTS idx_learning_journeys_status
ON learning_journeys(status);


CREATE INDEX IF NOT EXISTS idx_learning_journeys_stage
ON learning_journeys(current_stage);


CREATE INDEX IF NOT EXISTS idx_learning_journeys_last_activity
ON learning_journeys(last_activity_at);


-- Prevent multiple active journeys for the
-- same user and farming type.
CREATE UNIQUE INDEX IF NOT EXISTS uq_active_learning_journey
ON learning_journeys(user_id, farming_type_id)
WHERE status IN ('active', 'paused');



-- ============================================
-- AI LEARNING MESSAGES
-- ============================================
-- Stores the continuous conversation between
-- the user and Agro-Shield AI.
--
-- Examples:
--
-- User:
-- "I want to start poultry farming."
--
-- AI:
-- "What type of poultry are you interested in?"
--
-- User:
-- "Broilers."
--
-- AI:
-- Provides personalized guidance.
-- ============================================

CREATE TABLE IF NOT EXISTS learning_messages (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    journey_id INTEGER NOT NULL,

    sender_type TEXT NOT NULL,

    message_type TEXT NOT NULL DEFAULT 'text',

    content TEXT NOT NULL,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,


    CONSTRAINT fk_learning_messages_journey
        FOREIGN KEY (journey_id)
        REFERENCES learning_journeys(id)
        ON DELETE CASCADE,


    CONSTRAINT learning_messages_sender_type_check
        CHECK (
            sender_type IN (
                'user',
                'ai',
                'system'
            )
        ),


    CONSTRAINT learning_messages_type_check
        CHECK (
            message_type IN (
                'text',
                'guidance',
                'recommendation',
                'question',
                'milestone',
                'warning'
            )
        ),


    CONSTRAINT learning_messages_content_nonblank
        CHECK (
            BTRIM(content) <> ''
        )
);


CREATE INDEX IF NOT EXISTS idx_learning_messages_journey_id
ON learning_messages(journey_id);


CREATE INDEX IF NOT EXISTS idx_learning_messages_created_at
ON learning_messages(created_at);


CREATE INDEX IF NOT EXISTS idx_learning_messages_journey_created
ON learning_messages(journey_id, created_at);



-- ============================================
-- LEARNING CHECKPOINTS
-- ============================================
-- Tracks preparation and readiness.
--
-- The AI can create/check different
-- preparation requirements depending on
-- the farming type.
--
-- Examples:
--
-- Poultry:
--   housing_ready
--   water_available
--   feeding_plan_ready
--
-- Fisheries:
--   pond_ready
--   water_source_available
--   fingerlings_source_identified
--
-- Crop:
--   land_available
--   seed_source_identified
--   soil_preparation_understood
--
-- We intentionally store checkpoint_key as
-- data rather than creating separate columns
-- for every farming type.
-- ============================================

CREATE TABLE IF NOT EXISTS learning_checkpoints (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    journey_id INTEGER NOT NULL,

    checkpoint_key TEXT NOT NULL,

    title TEXT NOT NULL,

    description TEXT,

    status TEXT NOT NULL DEFAULT 'pending',

    progress INTEGER NOT NULL DEFAULT 0,

    notes TEXT,

    completed_at TIMESTAMP,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,


    CONSTRAINT fk_learning_checkpoints_journey
        FOREIGN KEY (journey_id)
        REFERENCES learning_journeys(id)
        ON DELETE CASCADE,


    CONSTRAINT learning_checkpoints_key_nonblank
        CHECK (
            BTRIM(checkpoint_key) <> ''
        ),


    CONSTRAINT learning_checkpoints_title_nonblank
        CHECK (
            BTRIM(title) <> ''
        ),


    CONSTRAINT learning_checkpoints_description_check
        CHECK (
            description IS NULL
            OR BTRIM(description) <> ''
        ),


    CONSTRAINT learning_checkpoints_notes_check
        CHECK (
            notes IS NULL
            OR BTRIM(notes) <> ''
        ),


    CONSTRAINT learning_checkpoints_status_check
        CHECK (
            status IN (
                'pending',
                'in_progress',
                'completed',
                'not_applicable'
            )
        ),


    CONSTRAINT learning_checkpoints_progress_check
        CHECK (
            progress >= 0
            AND progress <= 100
        ),


    CONSTRAINT learning_checkpoints_completion_check
        CHECK (
            (
                status = 'completed'
                AND progress = 100
                AND completed_at IS NOT NULL
            )
            OR
            (
                status <> 'completed'
            )
        ),


    CONSTRAINT learning_checkpoints_completed_at_check
        CHECK (
            completed_at IS NULL
            OR completed_at >= created_at
        ),


    CONSTRAINT unique_journey_checkpoint
        UNIQUE (
            journey_id,
            checkpoint_key
        )
);


CREATE INDEX IF NOT EXISTS idx_learning_checkpoints_journey_id
ON learning_checkpoints(journey_id);


CREATE INDEX IF NOT EXISTS idx_learning_checkpoints_status
ON learning_checkpoints(status);


CREATE INDEX IF NOT EXISTS idx_learning_checkpoints_journey_status
ON learning_checkpoints(journey_id, status);