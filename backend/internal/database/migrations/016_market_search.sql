CREATE TABLE IF NOT EXISTS marketplace_searches (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    search_term TEXT NOT NULL,
    normalized_produce TEXT,
    location TEXT,
    user_id INTEGER,
    session_id TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_marketplace_searches_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_marketplace_searches_term_time
    ON marketplace_searches(normalized_produce, created_at);

CREATE INDEX IF NOT EXISTS idx_marketplace_searches_location_time
    ON marketplace_searches(location, created_at);