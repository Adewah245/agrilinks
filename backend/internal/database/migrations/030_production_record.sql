CREATE TABLE IF NOT EXISTS production_records (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    farming_activity_id INTEGER NOT NULL,
    recorded_by INTEGER NOT NULL,

    output_name TEXT NOT NULL,
    output_category TEXT,

    quantity DOUBLE PRECISION NOT NULL,
    unit TEXT NOT NULL,

    production_date DATE NOT NULL DEFAULT CURRENT_DATE,

    quality_status TEXT,
    notes TEXT,

    metadata JSONB,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    FOREIGN KEY (farming_activity_id)
        REFERENCES farming_activities(id)
        ON DELETE CASCADE,

    FOREIGN KEY (recorded_by)
        REFERENCES users(id)
        ON DELETE RESTRICT,

    CHECK (TRIM(output_name) <> ''),
    CHECK (quantity > 0),
    CHECK (TRIM(unit) <> ''),
    CHECK (
        output_category IS NULL
        OR TRIM(output_category) <> ''
    ),
    CHECK (
        quality_status IS NULL
        OR TRIM(quality_status) <> ''
    ),
    CHECK (
        notes IS NULL
        OR TRIM(notes) <> ''
    )
);

CREATE INDEX IF NOT EXISTS idx_production_records_activity
    ON production_records(farming_activity_id);

CREATE INDEX IF NOT EXISTS idx_production_records_recorded_by
    ON production_records(recorded_by);

CREATE INDEX IF NOT EXISTS idx_production_records_output_category
    ON production_records(output_category);

CREATE INDEX IF NOT EXISTS idx_production_records_production_date
    ON production_records(production_date);

CREATE INDEX IF NOT EXISTS idx_production_records_activity_date
    ON production_records(farming_activity_id, production_date);