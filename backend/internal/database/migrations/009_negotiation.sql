-- =============================================================
-- AGRO-SHIELD
-- Negotiations
--
-- Defines:
--   1. Product negotiations
--   2. Negotiation message/offer history
--
-- Negotiation flow:
--
--     Buyer
--       ↓
--     Product
--       ↓
--   Negotiation
--       ↓
--   Messages / Offers
--       ↓
--   Accepted Offer
--       ↓
--      Order
--
-- A product owner may be:
--   - a user
--   - an organization
--
-- Negotiation history is preserved instead of overwriting
-- previous offers.
-- =============================================================


-- =============================================================
-- NEGOTIATIONS
-- =============================================================

CREATE TABLE IF NOT EXISTS negotiations (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- =========================================================
    -- Product Being Negotiated
    -- =========================================================
    product_id INTEGER NOT NULL,

    -- =========================================================
    -- Buyer
    -- =========================================================
    buyer_id INTEGER NOT NULL,

    -- =========================================================
    -- Product Owner
    --
    -- Polymorphic ownership:
    --
    --   user         -> users.id
    --   organization -> organizations.id
    --
    -- The application/service layer must validate owner_id
    -- according to owner_type.
    -- =========================================================
    owner_type TEXT NOT NULL,

    owner_id INTEGER NOT NULL,

    -- =========================================================
    -- Negotiation Quantity
    --
    -- Unit comes from products.unit.
    -- =========================================================
    quantity DOUBLE PRECISION NOT NULL,

    -- =========================================================
    -- Negotiation Status
    -- =========================================================
    status TEXT NOT NULL DEFAULT 'open',

    -- =========================================================
    -- Negotiation Rounds
    --
    -- round_count = number of completed negotiation rounds.
    --
    -- max_rounds allows Agro-Shield to configure the maximum
    -- number of rounds for this negotiation.
    -- =========================================================
    round_count INTEGER NOT NULL DEFAULT 0,

    max_rounds INTEGER NOT NULL DEFAULT 15,

    -- =========================================================
    -- Timestamps
    -- =========================================================
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    expires_at TIMESTAMP,

    -- =========================================================
    -- Relationships
    -- =========================================================
    CONSTRAINT fk_negotiations_product
        FOREIGN KEY (product_id)
        REFERENCES products(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_negotiations_buyer
        FOREIGN KEY (buyer_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    -- =========================================================
    -- Validation
    -- =========================================================
    CONSTRAINT negotiations_owner_type_check
        CHECK (
            owner_type IN (
                'user',
                'organization'
            )
        ),

    CONSTRAINT negotiations_owner_id_check
        CHECK (owner_id > 0),

    CONSTRAINT negotiations_quantity_check
        CHECK (quantity > 0),

    CONSTRAINT negotiations_round_count_check
        CHECK (
            round_count >= 0
            AND round_count <= max_rounds
        ),

    CONSTRAINT negotiations_max_rounds_check
        CHECK (max_rounds > 0),

    CONSTRAINT negotiations_status_check
        CHECK (
            status IN (
                'open',
                'accepted',
                'rejected',
                'expired',
                'closed'
            )
        ),

    CONSTRAINT negotiations_expiry_check
        CHECK (
            expires_at IS NULL
            OR expires_at > created_at
        )
);


-- =============================================================
-- NEGOTIATION INDEXES
-- =============================================================

CREATE INDEX IF NOT EXISTS idx_negotiations_product_id
ON negotiations(product_id);

CREATE INDEX IF NOT EXISTS idx_negotiations_buyer_id
ON negotiations(buyer_id);

CREATE INDEX IF NOT EXISTS idx_negotiations_owner
ON negotiations(owner_type, owner_id);

CREATE INDEX IF NOT EXISTS idx_negotiations_status
ON negotiations(status);

CREATE INDEX IF NOT EXISTS idx_negotiations_expires_at
ON negotiations(expires_at);

CREATE INDEX IF NOT EXISTS idx_negotiations_created_at
ON negotiations(created_at);


-- =============================================================
-- NEGOTIATION MESSAGES
--
-- Every message/offer becomes a permanent record.
--
-- Example:
--
--   Buyer:
--     "Can you sell 100kg?"
--
--   Seller:
--     Offer: ₦150,000
--
--   Buyer:
--     Offer: ₦135,000
--
--   Seller:
--     Offer: ₦145,000
--
-- None of these messages should be overwritten.
-- =============================================================

CREATE TABLE IF NOT EXISTS negotiation_messages (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- =========================================================
    -- Negotiation
    -- =========================================================
    negotiation_id INTEGER NOT NULL,

    -- =========================================================
    -- Sender
    -- =========================================================
    sender_id INTEGER NOT NULL,

    -- =========================================================
    -- Message Type
    -- =========================================================
    message_type TEXT NOT NULL DEFAULT 'message',

    -- =========================================================
    -- Offer Amount
    --
    -- NULL for ordinary messages.
    -- A price is required for an actual offer.
    -- =========================================================
    offer_price DOUBLE PRECISION,

    -- =========================================================
    -- Message Content
    -- =========================================================
    message TEXT,

    -- =========================================================
    -- Offer State
    -- =========================================================
    offer_status TEXT NOT NULL DEFAULT 'none',

    -- =========================================================
    -- Timestamp
    -- =========================================================
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- =========================================================
    -- Relationships
    -- =========================================================
    CONSTRAINT fk_negotiation_messages_negotiation
        FOREIGN KEY (negotiation_id)
        REFERENCES negotiations(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_negotiation_messages_sender
        FOREIGN KEY (sender_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    -- =========================================================
    -- Message Type Validation
    -- =========================================================
    CONSTRAINT negotiation_messages_type_check
        CHECK (
            message_type IN (
                'message',
                'offer'
            )
        ),

    -- =========================================================
    -- Offer Price Validation
    --
    -- Ordinary message:
    --   offer_price must be NULL
    --
    -- Offer:
    --   offer_price must be greater than or equal to zero.
    -- =========================================================
    CONSTRAINT negotiation_messages_price_check
        CHECK (
            (
                message_type = 'message'
                AND offer_price IS NULL
            )
            OR
            (
                message_type = 'offer'
                AND offer_price IS NOT NULL
                AND offer_price >= 0
            )
        ),

    -- =========================================================
    -- Message Content Validation
    --
    -- An offer may be sent without a message.
    -- A normal message must contain text.
    -- =========================================================
    CONSTRAINT negotiation_messages_content_check
        CHECK (
            message_type = 'offer'
            OR (
                message IS NOT NULL
                AND BTRIM(message) <> ''
            )
        ),

    -- =========================================================
    -- Offer Status Validation
    -- =========================================================
    CONSTRAINT negotiation_messages_offer_status_check
        CHECK (
            offer_status IN (
                'none',
                'pending',
                'accepted',
                'rejected'
            )
        ),

    -- =========================================================
    -- Offer Status Consistency
    --
    -- Ordinary messages cannot have an offer state.
    -- =========================================================
    CONSTRAINT negotiation_messages_offer_state_check
        CHECK (
            (
                message_type = 'message'
                AND offer_status = 'none'
            )
            OR
            (
                message_type = 'offer'
            )
        )
);


-- =============================================================
-- NEGOTIATION MESSAGE INDEXES
-- =============================================================

CREATE INDEX IF NOT EXISTS idx_negotiation_messages_negotiation_id
ON negotiation_messages(negotiation_id);

CREATE INDEX IF NOT EXISTS idx_negotiation_messages_sender_id
ON negotiation_messages(sender_id);

CREATE INDEX IF NOT EXISTS idx_negotiation_messages_created_at
ON negotiation_messages(created_at);

CREATE INDEX IF NOT EXISTS idx_negotiation_messages_offer_status
ON negotiation_messages(offer_status);

CREATE INDEX IF NOT EXISTS idx_negotiation_messages_type
ON negotiation_messages(message_type);