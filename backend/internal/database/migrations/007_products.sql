ON product_favorites(user_id);

CREATE INDEX IF NOT EXISTS idx_product_favorites_product
ON product_favorites(product_id);


-- ============================================================
-- PRODUCT STATUS HISTORY
--
-- Keeps a record of important product listing lifecycle changes.
--
-- Examples:
--   inactive -> active
--   active   -> sold_out
--   sold_out -> active
--   active   -> inactive
--
-- This is different from inventory_history.
--
-- inventory_history answers:
--   "What happened to the quantity?"
--
-- product_status_history answers:
--   "What happened to the listing?"
-- ============================================================

CREATE TABLE IF NOT EXISTS product_status_history (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    product_id INTEGER NOT NULL,

    old_status TEXT,

    new_status TEXT NOT NULL,

    reason TEXT,

    changed_by_type TEXT,

    changed_by_id INTEGER,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT product_status_history_new_status_check
        CHECK (
            new_status IN (
                'active',
                'sold_out',
                'inactive'
            )
        ),

    CONSTRAINT product_status_history_old_status_check
        CHECK (
            old_status IS NULL
            OR old_status IN (
                'active',
                'sold_out',
                'inactive'
            )
        ),

    CONSTRAINT product_status_history_changed_by_type_check
        CHECK (
            changed_by_type IS NULL
            OR changed_by_type IN (
                'user',
                'organization',
                'system'
            )
        ),

    CONSTRAINT fk_product_status_history_product
        FOREIGN KEY (product_id)
        REFERENCES products(id)
        ON DELETE CASCADE
);


CREATE INDEX IF NOT EXISTS idx_product_status_history_product
ON product_status_history(product_id);

CREATE INDEX IF NOT EXISTS idx_product_status_history_created
ON product_status_history(created_at);

CREATE INDEX IF NOT EXISTS idx_product_status_history_status
ON product_status_history(new_status);
