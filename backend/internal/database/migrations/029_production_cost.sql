-- ============================================================
-- 029_production_costs.sql
-- Farming Production Costs
-- Supports all farming types
-- ============================================================

CREATE TABLE IF NOT EXISTS production_costs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    farming_activity_id INTEGER NOT NULL,

    recorded_by INTEGER NOT NULL,

    category TEXT NOT NULL,

    description TEXT,

    quantity DOUBLE PRECISION,

    unit TEXT,

    unit_cost NUMERIC(20,2) NOT NULL,

    total_cost NUMERIC(20,2) NOT NULL,

    cost_date DATE NOT NULL DEFAULT CURRENT_DATE,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_production_costs_activity
        FOREIGN KEY (farming_activity_id)
        REFERENCES farming_activities(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_production_costs_recorder
        FOREIGN KEY (recorded_by)
        REFERENCES users(id)
        ON DELETE RESTRICT,

    CONSTRAINT production_costs_category_nonblank
        CHECK (BTRIM(category) <> ''),

    CONSTRAINT production_costs_description_check
        CHECK (
            description IS NULL
            OR BTRIM(description) <> ''
        ),

    CONSTRAINT production_costs_quantity_check
        CHECK (
            quantity IS NULL
            OR quantity > 0
        ),

    CONSTRAINT production_costs_unit_check
        CHECK (
            quantity IS NULL
            OR (
                unit IS NOT NULL
                AND BTRIM(unit) <> ''
            )
        ),

    CONSTRAINT production_costs_unit_cost_check
        CHECK (unit_cost >= 0),

    CONSTRAINT production_costs_total_cost_check
        CHECK (total_cost >= 0)
);


CREATE INDEX IF NOT EXISTS idx_production_costs_activity_id
    ON production_costs(farming_activity_id);

CREATE INDEX IF NOT EXISTS idx_production_costs_recorded_by
    ON production_costs(recorded_by);

CREATE INDEX IF NOT EXISTS idx_production_costs_category
    ON production_costs(category);

CREATE INDEX IF NOT EXISTS idx_production_costs_cost_date
    ON production_costs(cost_date);

CREATE INDEX IF NOT EXISTS idx_production_costs_activity_date
    ON production_costs(farming_activity_id, cost_date DESC);