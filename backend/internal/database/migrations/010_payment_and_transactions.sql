-- ============================================
-- TRANSACTIONS
-- ============================================

CREATE TABLE IF NOT EXISTS transactions (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,


    order_id INTEGER NOT NULL,


    buyer_id INTEGER NOT NULL,


    seller_type TEXT NOT NULL,


    seller_id INTEGER NOT NULL,


    amount DOUBLE PRECISION NOT NULL,


    currency TEXT NOT NULL DEFAULT 'NGN',


    payment_method TEXT,


    payment_reference TEXT UNIQUE,


    payment_provider TEXT,


    status TEXT NOT NULL DEFAULT 'pending',


    paid_at TIMESTAMP,


    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,


    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,


    CONSTRAINT fk_transaction_order
        FOREIGN KEY (order_id)
        REFERENCES orders(id)
        ON DELETE CASCADE,


    CONSTRAINT fk_transaction_buyer
        FOREIGN KEY (buyer_id)
        REFERENCES users(id)
        ON DELETE CASCADE,


    CONSTRAINT transaction_seller_type_check
        CHECK (
            seller_type IN (
                'farmer',
                'organization'
            )
        ),


    CONSTRAINT transaction_status_check
        CHECK (
            status IN (
                'pending',
                'successful',
                'failed',
                'cancelled',
                'refunded'
            )
        )
);



CREATE INDEX IF NOT EXISTS idx_transactions_order
ON transactions(order_id);



CREATE INDEX IF NOT EXISTS idx_transactions_buyer
ON transactions(buyer_id);



CREATE INDEX IF NOT EXISTS idx_transactions_status
ON transactions(status);



CREATE INDEX IF NOT EXISTS idx_transactions_reference
ON transactions(payment_reference);



-- ============================================
-- FARMER WALLET / EARNINGS
-- ============================================

CREATE TABLE IF NOT EXISTS wallets (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,


    owner_type TEXT NOT NULL,


    owner_id INTEGER NOT NULL,


    balance DOUBLE PRECISION NOT NULL DEFAULT 0,


    currency TEXT NOT NULL DEFAULT 'NGN',


    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,


    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,


    CONSTRAINT wallets_owner_type_check
        CHECK (
            owner_type IN (
                'farmer',
                'organization'
            )
        )
);



CREATE INDEX IF NOT EXISTS idx_wallets_owner
ON wallets(owner_type, owner_id);



-- ============================================
-- WALLET TRANSACTION HISTORY
-- ============================================

CREATE TABLE IF NOT EXISTS wallet_transactions (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,


    wallet_id INTEGER NOT NULL,


    transaction_type TEXT NOT NULL,


    amount DOUBLE PRECISION NOT NULL,


    description TEXT,


    reference_id INTEGER,


    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,


    CONSTRAINT fk_wallet_transaction_wallet
        FOREIGN KEY (wallet_id)
        REFERENCES wallets(id)
        ON DELETE CASCADE,


    CONSTRAINT wallet_transaction_type_check
        CHECK (
            transaction_type IN (
                'credit',
                'debit'
            )
        )
);



CREATE INDEX IF NOT EXISTS idx_wallet_transactions_wallet
ON wallet_transactions(wallet_id);