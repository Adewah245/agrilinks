-- =============================================================
-- AGRO-SHIELD
-- Migration 011: Payments & Transactions
--
-- Defines:
--   1. Payment transactions
--   2. User/organization wallets
--   3. Wallet transaction history
--
-- Financial flow:
--
--     Order
--       ↓
--     Payment Transaction
--       ↓
--   Successful Payment
--       ↓
--     Seller Wallet
--       ↓
--   Wallet Ledger
--
-- Important:
--
-- Payments are financial records.
-- Therefore financial amounts use NUMERIC instead of
-- DOUBLE PRECISION to avoid floating-point rounding problems.
--
-- IMPORTANT MIGRATION DEPENDENCY:
--
-- orders is created later in migration 021_order.sql.
--
-- Therefore this migration intentionally does NOT create the
-- foreign key from transactions.order_id to orders(id).
--
-- The foreign key will be added after the orders table exists.
-- =============================================================


-- =============================================================
-- TRANSACTIONS
-- =============================================================

CREATE TABLE IF NOT EXISTS transactions (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- =========================================================
    -- Order
    --
    -- Multiple transaction records may belong to one order
    -- because payment attempts can fail and be retried.
    --
    -- The foreign key to orders(id) is added later after the
    -- orders table has been created by migration 021.
    -- =========================================================
    order_id INTEGER NOT NULL,

    -- =========================================================
    -- Buyer
    -- =========================================================
    buyer_id INTEGER NOT NULL,

    -- =========================================================
    -- Seller
    --
    -- Follows the same ownership model used by products:
    --
    --   user
    --   organization
    -- =========================================================
    seller_type TEXT NOT NULL,

    seller_id INTEGER NOT NULL,

    -- =========================================================
    -- Financial Information
    -- =========================================================
    amount NUMERIC(20,2) NOT NULL,

    currency TEXT NOT NULL DEFAULT 'NGN',

    -- =========================================================
    -- Payment Information
    -- =========================================================
    payment_method TEXT,

    payment_reference TEXT UNIQUE,

    payment_provider TEXT,

    -- =========================================================
    -- Payment Status
    -- =========================================================
    status TEXT NOT NULL DEFAULT 'pending',

    -- =========================================================
    -- Payment Timestamp
    -- =========================================================
    paid_at TIMESTAMP,

    -- =========================================================
    -- General Timestamps
    -- =========================================================
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- =========================================================
    -- Buyer Relationship
    -- =========================================================
    CONSTRAINT fk_transactions_buyer
        FOREIGN KEY (buyer_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    -- =========================================================
    -- Seller Validation
    -- =========================================================
    CONSTRAINT transactions_seller_type_check
        CHECK (
            seller_type IN (
                'user',
                'organization'
            )
        ),

    CONSTRAINT transactions_seller_id_check
        CHECK (seller_id > 0),

    -- =========================================================
    -- Financial Validation
    -- =========================================================
    CONSTRAINT transactions_amount_check
        CHECK (amount >= 0),

    CONSTRAINT transactions_currency_check
        CHECK (BTRIM(currency) <> ''),

    -- =========================================================
    -- Optional Payment Fields
    -- =========================================================
    CONSTRAINT transactions_payment_method_check
        CHECK (
            payment_method IS NULL
            OR BTRIM(payment_method) <> ''
        ),

    CONSTRAINT transactions_payment_provider_check
        CHECK (
            payment_provider IS NULL
            OR BTRIM(payment_provider) <> ''
        ),

    -- =========================================================
    -- Status Validation
    -- =========================================================
    CONSTRAINT transactions_status_check
        CHECK (
            status IN (
                'pending',
                'successful',
                'failed',
                'cancelled',
                'refunded'
            )
        ),

    -- =========================================================
    -- Successful Payment Consistency
    -- =========================================================
    CONSTRAINT transactions_paid_at_check
        CHECK (
            status <> 'successful'
            OR paid_at IS NOT NULL
        )
);


-- =============================================================
-- TRANSACTION INDEXES
-- =============================================================

CREATE INDEX IF NOT EXISTS idx_transactions_order_id
ON transactions(order_id);

CREATE INDEX IF NOT EXISTS idx_transactions_buyer_id
ON transactions(buyer_id);

CREATE INDEX IF NOT EXISTS idx_transactions_seller
ON transactions(seller_type, seller_id);

CREATE INDEX IF NOT EXISTS idx_transactions_status
ON transactions(status);

CREATE INDEX IF NOT EXISTS idx_transactions_payment_reference
ON transactions(payment_reference);

CREATE INDEX IF NOT EXISTS idx_transactions_created_at
ON transactions(created_at);


-- =============================================================
-- WALLETS
--
-- A wallet belongs to:
--   - a user
--   - an organization
--
-- Wallets represent the current financial balance.
--
-- wallet_transactions is the audit trail.
--
-- The balance should be updated atomically by the backend when
-- a wallet transaction is created.
-- =============================================================

CREATE TABLE IF NOT EXISTS wallets (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- =========================================================
    -- Wallet Owner
    -- =========================================================
    owner_type TEXT NOT NULL,

    owner_id INTEGER NOT NULL,

    -- =========================================================
    -- Current Balance
    -- =========================================================
    balance NUMERIC(20,2) NOT NULL DEFAULT 0,

    currency TEXT NOT NULL DEFAULT 'NGN',

    -- =========================================================
    -- Timestamps
    -- =========================================================
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- =========================================================
    -- Validation
    -- =========================================================
    CONSTRAINT wallets_owner_type_check
        CHECK (
            owner_type IN (
                'user',
                'organization'
            )
        ),

    CONSTRAINT wallets_owner_id_check
        CHECK (owner_id > 0),

    CONSTRAINT wallets_balance_check
        CHECK (balance >= 0),

    CONSTRAINT wallets_currency_check
        CHECK (BTRIM(currency) <> ''),

    -- =========================================================
    -- One wallet per owner per currency.
    --
    -- This still allows future multi-currency support.
    -- =========================================================
    CONSTRAINT uq_wallet_owner_currency
        UNIQUE (owner_type, owner_id, currency)
);


-- =============================================================
-- WALLET INDEXES
-- =============================================================

CREATE INDEX IF NOT EXISTS idx_wallets_owner
ON wallets(owner_type, owner_id);

CREATE INDEX IF NOT EXISTS idx_wallets_currency
ON wallets(currency);


-- =============================================================
-- WALLET TRANSACTION HISTORY
--
-- This is the immutable financial ledger for a wallet.
--
-- Examples:
--
--   credit ₦150,000 -> successful product sale
--   debit  ₦20,000  -> withdrawal
--   credit ₦50,000  -> refund
--
-- The wallet balance is the current state.
-- The wallet transaction history explains how that balance
-- was produced.
-- =============================================================

CREATE TABLE IF NOT EXISTS wallet_transactions (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    wallet_id INTEGER NOT NULL,

    -- =========================================================
    -- Ledger Entry Type
    -- =========================================================
    transaction_type TEXT NOT NULL,

    -- =========================================================
    -- Amount
    -- =========================================================
    amount NUMERIC(20,2) NOT NULL,

    -- =========================================================
    -- Description
    -- =========================================================
    description TEXT,

    -- =========================================================
    -- Optional Reference
    --
    -- Examples:
    --
    -- payment transaction
    -- order
    -- withdrawal
    -- refund
    --
    -- The application layer interprets reference_id according
    -- to the transaction context.
    -- =========================================================
    reference_type TEXT,

    reference_id INTEGER,

    -- =========================================================
    -- Timestamp
    -- =========================================================
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- =========================================================
    -- Relationship
    -- =========================================================
    CONSTRAINT fk_wallet_transactions_wallet
        FOREIGN KEY (wallet_id)
        REFERENCES wallets(id)
        ON DELETE CASCADE,

    -- =========================================================
    -- Validation
    -- =========================================================
    CONSTRAINT wallet_transactions_type_check
        CHECK (
            transaction_type IN (
                'credit',
                'debit'
            )
        ),

    CONSTRAINT wallet_transactions_amount_check
        CHECK (amount > 0),

    CONSTRAINT wallet_transactions_description_check
        CHECK (
            description IS NULL
            OR BTRIM(description) <> ''
        ),

    CONSTRAINT wallet_transactions_reference_check
        CHECK (
            (
                reference_type IS NULL
                AND reference_id IS NULL
            )
            OR
            (
                reference_type IS NOT NULL
                AND BTRIM(reference_type) <> ''
                AND reference_id IS NOT NULL
                AND reference_id > 0
            )
        )
);


-- =============================================================
-- WALLET TRANSACTION INDEXES
-- =============================================================

CREATE INDEX IF NOT EXISTS idx_wallet_transactions_wallet_id
ON wallet_transactions(wallet_id);

CREATE INDEX IF NOT EXISTS idx_wallet_transactions_type
ON wallet_transactions(transaction_type);

CREATE INDEX IF NOT EXISTS idx_wallet_transactions_created_at
ON wallet_transactions(created_at);

CREATE INDEX IF NOT EXISTS idx_wallet_transactions_reference
ON wallet_transactions(reference_type, reference_id);