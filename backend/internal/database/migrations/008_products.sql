-- =============================================================
-- AGRO-SHIELD
-- Products & Marketplace Inventory
--
-- Defines:
--   1. Products
--   2. Product images
--   3. Product price history
--   4. Inventory history
--   5. Product favorites
--   6. Product status history
--
-- A product may belong to:
--   - a user
--   - an organization
--
-- This table is intentionally broader than "crops".
-- Agro-Shield supports:
--   - Crop products
--   - Livestock
--   - Poultry
--   - Fisheries
--   - Beekeeping
--   - Other agricultural products
-- =============================================================


-- =============================================================
-- PRODUCTS
-- =============================================================

CREATE TABLE IF NOT EXISTS products (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- =========================================================
    -- Ownership
    --
    -- Polymorphic ownership:
    --   user         -> users.id
    --   organization -> organizations.id
    --
    -- PostgreSQL cannot enforce both possible foreign keys with
    -- this structure, so application/service-layer validation
    -- must verify owner_id according to owner_type.
    -- =========================================================
    owner_type TEXT NOT NULL,

    owner_id INTEGER NOT NULL,

    -- =========================================================
    -- Product Information
    -- =========================================================
    name TEXT NOT NULL,

    description TEXT,

    category TEXT NOT NULL,

    quantity DOUBLE PRECISION NOT NULL DEFAULT 0,

    unit TEXT NOT NULL,

    -- =========================================================
    -- Pricing
    -- =========================================================
    price DOUBLE PRECISION NOT NULL DEFAULT 0,

    -- =========================================================
    -- Location
    --
    -- Location hierarchy:
    --
    --     State
    --       ↓
    --      LGA
    --       ↓
    --   Community
    --
    -- GPS coordinates are kept separately because they represent
    -- the actual geographic position of the product/farm/storage
    -- location.
    -- =========================================================
    state_id INTEGER,

    lga_id INTEGER,

    community_id INTEGER,

    latitude DOUBLE PRECISION,

    longitude DOUBLE PRECISION,

    location_accuracy DOUBLE PRECISION,

    -- =========================================================
    -- Listing Lifecycle
    -- =========================================================
    status TEXT NOT NULL DEFAULT 'active',

    initial_listed_quantity DOUBLE PRECISION,

    first_listed_at TIMESTAMP,

    first_order_at TIMESTAMP,

    sold_out_at TIMESTAMP,

    -- =========================================================
    -- Timestamps
    -- =========================================================
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- =========================================================
    -- Validation
    -- =========================================================
    CONSTRAINT products_owner_type_check
        CHECK (
            owner_type IN (
                'user',
                'organization'
            )
        ),

    CONSTRAINT products_owner_id_check
        CHECK (owner_id > 0),

    CONSTRAINT products_name_nonblank
        CHECK (BTRIM(name) <> ''),

    CONSTRAINT products_category_nonblank
        CHECK (BTRIM(category) <> ''),

    CONSTRAINT products_unit_nonblank
        CHECK (BTRIM(unit) <> ''),

    CONSTRAINT products_quantity_check
        CHECK (quantity >= 0),

    CONSTRAINT products_price_check
        CHECK (price >= 0),

    CONSTRAINT products_initial_quantity_check
        CHECK (
            initial_listed_quantity IS NULL
            OR initial_listed_quantity >= 0
        ),

    CONSTRAINT products_latitude_check
        CHECK (
            latitude IS NULL
            OR (
                latitude >= -90
                AND latitude <= 90
            )
        ),

    CONSTRAINT products_longitude_check
        CHECK (
            longitude IS NULL
            OR (
                longitude >= -180
                AND longitude <= 180
            )
        ),

    CONSTRAINT products_location_accuracy_check
        CHECK (
            location_accuracy IS NULL
            OR location_accuracy >= 0
        ),

    CONSTRAINT products_status_check
        CHECK (
            status IN (
                'active',
                'sold_out',
                'inactive'
            )
        ),

    -- =========================================================
    -- Relationships
    -- =========================================================
    CONSTRAINT fk_products_state
        FOREIGN KEY (state_id)
        REFERENCES states(id)
        ON DELETE SET NULL,

    CONSTRAINT fk_products_lga
        FOREIGN KEY (lga_id)
        REFERENCES lgas(id)
        ON DELETE SET NULL,

    CONSTRAINT fk_products_community
        FOREIGN KEY (community_id)
        REFERENCES communities(id)
        ON DELETE SET NULL
);


-- =============================================================
-- PRODUCT INDEXES
-- =============================================================

CREATE INDEX IF NOT EXISTS idx_products_owner
ON products(owner_type, owner_id);

CREATE INDEX IF NOT EXISTS idx_products_category
ON products(category);

CREATE INDEX IF NOT EXISTS idx_products_state_id
ON products(state_id);

CREATE INDEX IF NOT EXISTS idx_products_lga_id
ON products(lga_id);

CREATE INDEX IF NOT EXISTS idx_products_community_id
ON products(community_id);

CREATE INDEX IF NOT EXISTS idx_products_status
ON products(status);

CREATE INDEX IF NOT EXISTS idx_products_created_at
ON products(created_at);


-- =============================================================
-- PRODUCT IMAGES
-- =============================================================

CREATE TABLE IF NOT EXISTS product_images (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    product_id INTEGER NOT NULL,

    image_url TEXT NOT NULL,

    is_primary BOOLEAN NOT NULL DEFAULT FALSE,

    sort_order INTEGER NOT NULL DEFAULT 0,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- =========================================================
    -- Relationships
    -- =========================================================
    CONSTRAINT fk_product_images_product
        FOREIGN KEY (product_id)
        REFERENCES products(id)
        ON DELETE CASCADE,

    -- =========================================================
    -- Validation
    -- =========================================================
    CONSTRAINT product_images_url_nonblank
        CHECK (BTRIM(image_url) <> ''),

    CONSTRAINT product_images_sort_order_check
        CHECK (sort_order >= 0)
);


CREATE INDEX IF NOT EXISTS idx_product_images_product_id
ON product_images(product_id);

CREATE INDEX IF NOT EXISTS idx_product_images_primary
ON product_images(product_id, is_primary);

CREATE INDEX IF NOT EXISTS idx_product_images_sort_order
ON product_images(product_id, sort_order);


-- =============================================================
-- PRODUCT PRICE HISTORY
--
-- Permanent record of product price changes.
--
-- Supports:
--   - Price history
--   - Market trends
--   - Price analytics
--   - AI price recommendations
--   - Historical market intelligence
-- =============================================================

CREATE TABLE IF NOT EXISTS product_price_history (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    product_id INTEGER NOT NULL,

    price DOUBLE PRECISION NOT NULL,

    unit TEXT NOT NULL,

    source TEXT NOT NULL DEFAULT 'Agro-Shield',

    recorded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- =========================================================
    -- Validation
    -- =========================================================
    CONSTRAINT product_price_history_price_check
        CHECK (price >= 0),

    CONSTRAINT product_price_history_unit_nonblank
        CHECK (BTRIM(unit) <> ''),

    CONSTRAINT product_price_history_source_nonblank
        CHECK (BTRIM(source) <> ''),

    -- =========================================================
    -- Relationship
    -- =========================================================
    CONSTRAINT fk_product_price_history_product
        FOREIGN KEY (product_id)
        REFERENCES products(id)
        ON DELETE CASCADE
);


CREATE INDEX IF NOT EXISTS idx_product_price_history_product_id
ON product_price_history(product_id);

CREATE INDEX IF NOT EXISTS idx_product_price_history_recorded_at
ON product_price_history(recorded_at);


-- =============================================================
-- INVENTORY HISTORY
--
-- Permanent record of quantity changes.
--
-- Examples:
--
--   +500 kg  -> stock added
--   -100 kg  -> order
--   -50 kg   -> damaged/lost
--   +300 kg  -> replenished
--
-- inventory_history answers:
--
--   "What happened to the quantity?"
--
-- =============================================================

CREATE TABLE IF NOT EXISTS inventory_history (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    product_id INTEGER NOT NULL,

    quantity_before DOUBLE PRECISION NOT NULL,

    quantity_change DOUBLE PRECISION NOT NULL,

    quantity_after DOUBLE PRECISION NOT NULL,

    reason TEXT NOT NULL,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- =========================================================
    -- Validation
    -- =========================================================
    CONSTRAINT inventory_history_quantity_before_check
        CHECK (quantity_before >= 0),

    CONSTRAINT inventory_history_quantity_after_check
        CHECK (quantity_after >= 0),

    CONSTRAINT inventory_history_reason_nonblank
        CHECK (BTRIM(reason) <> ''),

    -- =========================================================
    -- Relationship
    -- =========================================================
    CONSTRAINT fk_inventory_history_product
        FOREIGN KEY (product_id)
        REFERENCES products(id)
        ON DELETE CASCADE
);


CREATE INDEX IF NOT EXISTS idx_inventory_history_product_id
ON inventory_history(product_id);

CREATE INDEX IF NOT EXISTS idx_inventory_history_created_at
ON inventory_history(created_at);

CREATE INDEX IF NOT EXISTS idx_inventory_history_reason
ON inventory_history(reason);


-- =============================================================
-- PRODUCT FAVORITES
--
-- Allows users to save products they are interested in.
--
-- Supports:
--   - Buyer wishlists
--   - Saved products
--   - Watchlists
--   - Future price-drop notifications
-- =============================================================

CREATE TABLE IF NOT EXISTS product_favorites (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id INTEGER NOT NULL,

    product_id INTEGER NOT NULL,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- =========================================================
    -- Prevent duplicate favorites
    -- =========================================================
    CONSTRAINT uq_product_favorite
        UNIQUE (user_id, product_id),

    -- =========================================================
    -- Relationships
    -- =========================================================
    CONSTRAINT fk_product_favorites_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_product_favorites_product
        FOREIGN KEY (product_id)
        REFERENCES products(id)
        ON DELETE CASCADE
);


CREATE INDEX IF NOT EXISTS idx_product_favorites_user_id
ON product_favorites(user_id);

CREATE INDEX IF NOT EXISTS idx_product_favorites_product_id
ON product_favorites(product_id);


-- =============================================================
-- PRODUCT STATUS HISTORY
--
-- Records listing lifecycle changes.
--
-- Examples:
--
--   inactive -> active
--   active   -> sold_out
--   sold_out -> active
--   active   -> inactive
--
-- This is different from inventory_history.
--
-- inventory_history:
--   "What happened to the quantity?"
--
-- product_status_history:
--   "What happened to the listing?"
-- =============================================================

CREATE TABLE IF NOT EXISTS product_status_history (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    product_id INTEGER NOT NULL,

    old_status TEXT,

    new_status TEXT NOT NULL,

    reason TEXT,

    changed_by_type TEXT,

    changed_by_id INTEGER,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- =========================================================
    -- Status Validation
    -- =========================================================
    CONSTRAINT product_status_history_new_status_check
        CHECK (
            new_status IN (
                'active',
                'sold_out',
                'inactive'
            )
        ),

    CONSTRAINT product_status_history_old_status_check
        CHECK (
            old_status IS NULL
            OR old_status IN (
                'active',
                'sold_out',
                'inactive'
            )
        ),

    -- =========================================================
    -- Actor Validation
    -- =========================================================
    CONSTRAINT product_status_history_changed_by_type_check
        CHECK (
            changed_by_type IS NULL
            OR changed_by_type IN (
                'user',
                'organization',
                'system'
            )
        ),

    CONSTRAINT product_status_history_changed_by_id_check
        CHECK (
            changed_by_id IS NULL
            OR changed_by_id > 0
        ),

    CONSTRAINT product_status_history_reason_check
        CHECK (
            reason IS NULL
            OR BTRIM(reason) <> ''
        ),

    -- =========================================================
    -- Relationship
    -- =========================================================
    CONSTRAINT fk_product_status_history_product
        FOREIGN KEY (product_id)
        REFERENCES products(id)
        ON DELETE CASCADE
);


CREATE INDEX IF NOT EXISTS idx_product_status_history_product_id
ON product_status_history(product_id);

CREATE INDEX IF NOT EXISTS idx_product_status_history_created_at
ON product_status_history(created_at);

CREATE INDEX IF NOT EXISTS idx_product_status_history_status
ON product_status_history(new_status);

CREATE INDEX IF NOT EXISTS idx_product_status_history_actor
ON product_status_history(changed_by_type, changed_by_id);