-- =============================================================
-- AGRO-SHIELD
-- Migration 007: Logistics & Delivery System
--
-- Defines:
--   1. Delivery partners
--   2. Deliveries
--   3. Delivery tracking/location history
--
-- IMPORTANT:
--
-- The orders table is created by migration 021.
-- Therefore deliveries.order_id is created here as a normal
-- column. The foreign key to orders will be added after the
-- orders table exists.
--
-- Location hierarchy:
--
--     State
--       ↓
--      LGA
--       ↓
--   Community
--
-- GPS tracking remains independent from the location hierarchy.
-- =============================================================


-- =============================================================
-- 1. DELIVERY PARTNERS
-- =============================================================

CREATE TABLE delivery_partners (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- =========================================================
    -- Organization
    -- A delivery partner may operate independently or belong
    -- to an organization.
    -- =========================================================
    organization_id INTEGER,

    -- =========================================================
    -- Partner Identity
    -- =========================================================
    name TEXT NOT NULL,

    phone TEXT NOT NULL,

    email TEXT,

    -- =========================================================
    -- Vehicle Information
    -- =========================================================
    vehicle_type TEXT,

    registration_number TEXT,

    -- =========================================================
    -- Operating Location
    -- =========================================================
    state_id INTEGER,

    lga_id INTEGER,

    -- =========================================================
    -- Verification / Status
    -- =========================================================
    verified BOOLEAN NOT NULL DEFAULT FALSE,

    status TEXT NOT NULL DEFAULT 'active',

    -- =========================================================
    -- Timestamps
    -- =========================================================
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,


    -- =========================================================
    -- Relationships
    -- =========================================================

    CONSTRAINT fk_delivery_partners_organization
        FOREIGN KEY (organization_id)
        REFERENCES organizations(id)
        ON DELETE SET NULL,

    CONSTRAINT fk_delivery_partners_state
        FOREIGN KEY (state_id)
        REFERENCES states(id)
        ON DELETE SET NULL,

    CONSTRAINT fk_delivery_partners_lga
        FOREIGN KEY (lga_id)
        REFERENCES lgas(id)
        ON DELETE SET NULL,


    -- =========================================================
    -- Validation
    -- =========================================================

    CONSTRAINT delivery_partners_name_nonblank
        CHECK (BTRIM(name) <> ''),

    CONSTRAINT delivery_partners_phone_nonblank
        CHECK (BTRIM(phone) <> ''),

    CONSTRAINT delivery_partners_email_check
        CHECK (
            email IS NULL
            OR BTRIM(email) <> ''
        ),

    CONSTRAINT delivery_partners_vehicle_type_check
        CHECK (
            vehicle_type IS NULL
            OR BTRIM(vehicle_type) <> ''
        ),

    CONSTRAINT delivery_partners_registration_check
        CHECK (
            registration_number IS NULL
            OR BTRIM(registration_number) <> ''
        ),

    CONSTRAINT delivery_partners_status_check
        CHECK (
            status IN (
                'active',
                'inactive',
                'suspended'
            )
        )
);


-- =============================================================
-- 2. DELIVERY PARTNER INDEXES
-- =============================================================

CREATE INDEX idx_delivery_partners_organization_id
ON delivery_partners(organization_id);

CREATE INDEX idx_delivery_partners_state_id
ON delivery_partners(state_id);

CREATE INDEX idx_delivery_partners_lga_id
ON delivery_partners(lga_id);

CREATE INDEX idx_delivery_partners_status
ON delivery_partners(status);

CREATE INDEX idx_delivery_partners_verified
ON delivery_partners(verified);


-- =============================================================
-- 3. DELIVERIES
-- =============================================================

CREATE TABLE deliveries (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- =========================================================
    -- Order
    --
    -- The foreign key is intentionally not created here because
    -- orders is created by migration 021.
    -- =========================================================
    order_id INTEGER NOT NULL UNIQUE,

    -- =========================================================
    -- Assigned Delivery Partner
    -- =========================================================
    delivery_partner_id INTEGER,

    -- =========================================================
    -- Pickup Address
    --
    -- Address is stored as a snapshot so that the delivery
    -- address remains available even if the user's profile
    -- location later changes.
    -- =========================================================
    pickup_address TEXT NOT NULL,

    pickup_state_id INTEGER,

    pickup_lga_id INTEGER,

    pickup_community_id INTEGER,

    -- =========================================================
    -- Destination Address
    -- =========================================================
    destination_address TEXT NOT NULL,

    destination_state_id INTEGER,

    destination_lga_id INTEGER,

    destination_community_id INTEGER,

    -- =========================================================
    -- Delivery Cost / Distance
    -- =========================================================
    delivery_fee NUMERIC(20,2) NOT NULL DEFAULT 0,

    distance_km NUMERIC(12,3),

    -- =========================================================
    -- Delivery Status
    -- =========================================================
    status TEXT NOT NULL DEFAULT 'pending',

    -- =========================================================
    -- Tracking
    -- =========================================================
    tracking_code TEXT UNIQUE,

    -- =========================================================
    -- Delivery Timestamps
    -- =========================================================
    picked_up_at TIMESTAMP,

    delivered_at TIMESTAMP,

    -- =========================================================
    -- General Timestamps
    -- =========================================================
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,


    -- =========================================================
    -- Delivery Partner Relationship
    -- =========================================================

    CONSTRAINT fk_deliveries_partner
        FOREIGN KEY (delivery_partner_id)
        REFERENCES delivery_partners(id)
        ON DELETE SET NULL,


    -- =========================================================
    -- Pickup Location Relationships
    -- =========================================================

    CONSTRAINT fk_deliveries_pickup_state
        FOREIGN KEY (pickup_state_id)
        REFERENCES states(id)
        ON DELETE SET NULL,

    CONSTRAINT fk_deliveries_pickup_lga
        FOREIGN KEY (pickup_lga_id)
        REFERENCES lgas(id)
        ON DELETE SET NULL,

    CONSTRAINT fk_deliveries_pickup_community
        FOREIGN KEY (pickup_community_id)
        REFERENCES communities(id)
        ON DELETE SET NULL,


    -- =========================================================
    -- Destination Location Relationships
    -- =========================================================

    CONSTRAINT fk_deliveries_destination_state
        FOREIGN KEY (destination_state_id)
        REFERENCES states(id)
        ON DELETE SET NULL,

    CONSTRAINT fk_deliveries_destination_lga
        FOREIGN KEY (destination_lga_id)
        REFERENCES lgas(id)
        ON DELETE SET NULL,

    CONSTRAINT fk_deliveries_destination_community
        FOREIGN KEY (destination_community_id)
        REFERENCES communities(id)
        ON DELETE SET NULL,


    -- =========================================================
    -- Validation
    -- =========================================================

    CONSTRAINT deliveries_pickup_address_nonblank
        CHECK (BTRIM(pickup_address) <> ''),

    CONSTRAINT deliveries_destination_address_nonblank
        CHECK (BTRIM(destination_address) <> ''),

    CONSTRAINT deliveries_fee_check
        CHECK (delivery_fee >= 0),

    CONSTRAINT deliveries_distance_check
        CHECK (
            distance_km IS NULL
            OR distance_km >= 0
        ),

    CONSTRAINT deliveries_status_check
        CHECK (
            status IN (
                'pending',
                'assigned',
                'picked_up',
                'in_transit',
                'delivered',
                'cancelled'
            )
        ),

    CONSTRAINT deliveries_picked_up_at_check
        CHECK (
            status NOT IN (
                'picked_up',
                'in_transit',
                'delivered'
            )
            OR picked_up_at IS NOT NULL
        ),

    CONSTRAINT deliveries_delivered_at_check
        CHECK (
            status <> 'delivered'
            OR delivered_at IS NOT NULL
        ),

    CONSTRAINT deliveries_delivery_time_check
        CHECK (
            delivered_at IS NULL
            OR picked_up_at IS NULL
            OR delivered_at >= picked_up_at
        )
);


