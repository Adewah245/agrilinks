-- ============================================
-- DELIVERY PARTNERS
-- ============================================

CREATE TABLE IF NOT EXISTS delivery_partners (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,


    organization_id INTEGER,


    name TEXT NOT NULL,


    phone TEXT NOT NULL,


    email TEXT,


    vehicle_type TEXT,


    registration_number TEXT,


    state_id INTEGER,


    lga_id INTEGER,


    verified BOOLEAN NOT NULL DEFAULT FALSE,


    status TEXT NOT NULL DEFAULT 'active',


    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,


    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,


    CONSTRAINT fk_delivery_partner_organization
        FOREIGN KEY (organization_id)
        REFERENCES organizations(id)
        ON DELETE SET NULL,


    CONSTRAINT fk_delivery_partner_state
        FOREIGN KEY (state_id)
        REFERENCES states(id)
        ON DELETE SET NULL,


    CONSTRAINT fk_delivery_partner_lga
        FOREIGN KEY (lga_id)
        REFERENCES lgas(id)
        ON DELETE SET NULL,


    CONSTRAINT delivery_partner_status_check
        CHECK (
            status IN (
                'active',
                'inactive',
                'suspended'
            )
        )
);



CREATE INDEX IF NOT EXISTS idx_delivery_partner_state
ON delivery_partners(state_id);



-- ============================================
-- DELIVERIES
-- ============================================

CREATE TABLE IF NOT EXISTS deliveries (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,


    order_id INTEGER NOT NULL,


    delivery_partner_id INTEGER,


    pickup_address TEXT NOT NULL,


    pickup_state_id INTEGER,


    pickup_lga_id INTEGER,


    destination_address TEXT NOT NULL,


    destination_state_id INTEGER,


    destination_lga_id INTEGER,


    delivery_fee DOUBLE PRECISION NOT NULL DEFAULT 0,


    distance_km DOUBLE PRECISION,


    status TEXT NOT NULL DEFAULT 'pending',


    tracking_code TEXT UNIQUE,


    picked_up_at TIMESTAMP,


    delivered_at TIMESTAMP,


    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,


    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,


    CONSTRAINT fk_delivery_order
        FOREIGN KEY (order_id)
        REFERENCES orders(id)
        ON DELETE CASCADE,


    CONSTRAINT fk_delivery_partner
        FOREIGN KEY (delivery_partner_id)
        REFERENCES delivery_partners(id)
        ON DELETE SET NULL,


    CONSTRAINT delivery_status_check
        CHECK (
            status IN (
                'pending',
                'assigned',
                'picked_up',
                'in_transit',
                'delivered',
                'cancelled'
            )
        )
);



CREATE INDEX IF NOT EXISTS idx_deliveries_order
ON deliveries(order_id);



CREATE INDEX IF NOT EXISTS idx_deliveries_status
ON deliveries(status);



CREATE INDEX IF NOT EXISTS idx_deliveries_tracking
ON deliveries(tracking_code);



-- ============================================
-- DELIVERY LOCATION HISTORY
-- ============================================

CREATE TABLE IF NOT EXISTS delivery_tracking (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,


    delivery_id INTEGER NOT NULL,


    latitude DOUBLE PRECISION,


    longitude DOUBLE PRECISION,


    location_name TEXT,


    note TEXT,


    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,


    CONSTRAINT fk_tracking_delivery
        FOREIGN KEY (delivery_id)
        REFERENCES deliveries(id)
        ON DELETE CASCADE
);



CREATE INDEX IF NOT EXISTS idx_delivery_tracking_delivery
ON delivery_tracking(delivery_id);