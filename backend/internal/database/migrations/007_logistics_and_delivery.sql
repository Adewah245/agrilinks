-- =============================================================
-- 5. DELIVERY TRACKING
-- =============================================================
--
-- Stores the GPS/location history of a delivery.
--
-- This is separate from states, LGAs and communities because
-- GPS coordinates represent the actual position of the delivery
-- vehicle at a particular point in time.
-- =============================================================

CREATE TABLE delivery_tracking (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    delivery_id INTEGER NOT NULL,

    -- =========================================================
    -- GPS Position
    -- =========================================================
    latitude DOUBLE PRECISION NOT NULL,

    longitude DOUBLE PRECISION NOT NULL,

    -- =========================================================
    -- Human-readable Location
    -- =========================================================
    location_name TEXT,

    -- =========================================================
    -- Tracking Note
    -- =========================================================
    note TEXT,

    -- =========================================================
    -- Timestamp
    -- =========================================================
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,


    -- =========================================================
    -- Relationship
    -- =========================================================

    CONSTRAINT fk_delivery_tracking_delivery
        FOREIGN KEY (delivery_id)
        REFERENCES deliveries(id)
        ON DELETE CASCADE,


    -- =========================================================
    -- GPS Validation
    -- =========================================================

    CONSTRAINT delivery_tracking_latitude_check
        CHECK (
            latitude >= -90
            AND latitude <= 90
        ),

    CONSTRAINT delivery_tracking_longitude_check
        CHECK (
            longitude >= -180
            AND longitude <= 180
        ),

    CONSTRAINT delivery_tracking_location_name_check
        CHECK (
            location_name IS NULL
            OR BTRIM(location_name) <> ''
        )
);


-- =============================================================
-- 6. DELIVERY TRACKING INDEXES
-- =============================================================

CREATE INDEX idx_delivery_tracking_delivery_id
ON delivery_tracking(delivery_id);

CREATE INDEX idx_delivery_tracking_created_at
ON delivery_tracking(created_at);