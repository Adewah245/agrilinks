-- =============================================================
-- 002_farming_types.sql
--
-- Defines the agricultural activities supported by Agro-Shield.
--
-- This table is intentionally independent of users and learning.
-- Users will be connected to farming types by later schemas.
-- =============================================================

CREATE TABLE IF NOT EXISTS farming_types (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- =========================================================
    -- Identity
    -- =========================================================
    name TEXT NOT NULL UNIQUE,

    slug TEXT NOT NULL UNIQUE,

    -- =========================================================
    -- Description
    -- General description of the farming activity.
    -- Detailed AI guidance will be handled separately.
    -- =========================================================
    description TEXT,

    -- =========================================================
    -- Timestamp
    -- =========================================================
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- =========================================================
    -- Validation
    -- =========================================================
    CONSTRAINT farming_types_name_nonblank
        CHECK (BTRIM(name) <> ''),

    CONSTRAINT farming_types_slug_nonblank
        CHECK (BTRIM(slug) <> '')
);


-- =============================================================
-- Indexes
-- =============================================================

CREATE INDEX IF NOT EXISTS idx_farming_types_name
ON farming_types(name);

CREATE INDEX IF NOT EXISTS idx_farming_types_slug
ON farming_types(slug);


