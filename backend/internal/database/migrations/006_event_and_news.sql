-- =============================================================
-- AGRO-SHIELD
-- Events & Public Announcements
--
-- Defines:
--   1. Public announcements
--   2. Agricultural events
--   3. Event registrations
--
-- Events can later be connected to:
--   - Organizations
--   - Farming types
--   - Learning spaces
--   - AI learning activities
--   - Agricultural communities
-- =============================================================


-- =============================================================
-- NEWS / PUBLIC ANNOUNCEMENTS
-- =============================================================

CREATE TABLE IF NOT EXISTS announcements (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- =========================================================
    -- Publisher
    -- =========================================================
    organization_id INTEGER,

    created_by INTEGER,

    -- =========================================================
    -- Content
    -- =========================================================
    title TEXT NOT NULL,

    content TEXT NOT NULL,

    category TEXT NOT NULL,

    image_url TEXT,

    -- =========================================================
    -- Publication Status
    -- =========================================================
    status TEXT NOT NULL DEFAULT 'draft',

    published_at TIMESTAMP,

    -- =========================================================
    -- Timestamps
    -- =========================================================
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- =========================================================
    -- Relationships
    -- =========================================================
    CONSTRAINT fk_announcements_organization
        FOREIGN KEY (organization_id)
        REFERENCES organizations(id)
        ON DELETE SET NULL,

    CONSTRAINT fk_announcements_creator
        FOREIGN KEY (created_by)
        REFERENCES users(id)
        ON DELETE SET NULL,

    -- =========================================================
    -- Validation
    -- =========================================================
    CONSTRAINT announcements_title_nonblank
        CHECK (BTRIM(title) <> ''),

    CONSTRAINT announcements_content_nonblank
        CHECK (BTRIM(content) <> ''),

    CONSTRAINT announcements_category_nonblank
        CHECK (BTRIM(category) <> ''),

    CONSTRAINT announcements_status_check
        CHECK (
            status IN (
                'draft',
                'published',
                'archived'
            )
        ),

    CONSTRAINT announcements_published_at_check
        CHECK (
            status <> 'published'
            OR published_at IS NOT NULL
        )
);


-- =============================================================
-- ANNOUNCEMENT INDEXES
-- =============================================================

CREATE INDEX IF NOT EXISTS idx_announcements_organization_id
ON announcements(organization_id);

CREATE INDEX IF NOT EXISTS idx_announcements_created_by
ON announcements(created_by);

CREATE INDEX IF NOT EXISTS idx_announcements_category
ON announcements(category);

CREATE INDEX IF NOT EXISTS idx_announcements_status
ON announcements(status);

CREATE INDEX IF NOT EXISTS idx_announcements_published_at
ON announcements(published_at);


-- =============================================================
-- AGRICULTURAL EVENTS
-- =============================================================

CREATE TABLE IF NOT EXISTS events (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- =========================================================
    -- Organizer
    -- =========================================================
    organization_id INTEGER,

    created_by INTEGER,

    -- =========================================================
    -- Event Information
    -- =========================================================
    title TEXT NOT NULL,

    description TEXT NOT NULL,

    event_type TEXT NOT NULL,

    venue TEXT NOT NULL,

    -- =========================================================
    -- Location
    -- =========================================================
    community_id INTEGER,

    state_id INTEGER,

    lga_id INTEGER,

    -- =========================================================
    -- Schedule
    -- =========================================================
    start_date TIMESTAMP NOT NULL,

    end_date TIMESTAMP,

    -- =========================================================
    -- Registration
    -- =========================================================
    registration_required BOOLEAN NOT NULL DEFAULT FALSE,

    registration_link TEXT,

    max_participants INTEGER,

    -- =========================================================
    -- Status
    -- =========================================================
    status TEXT NOT NULL DEFAULT 'upcoming',

    -- =========================================================
    -- Timestamps
    -- =========================================================
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- =========================================================
    -- Relationships
    -- =========================================================
    CONSTRAINT fk_events_organization
        FOREIGN KEY (organization_id)
        REFERENCES organizations(id)
        ON DELETE SET NULL,

    CONSTRAINT fk_events_creator
        FOREIGN KEY (created_by)
        REFERENCES users(id)
        ON DELETE SET NULL,

    CONSTRAINT fk_events_community
        FOREIGN KEY (community_id)
        REFERENCES communities(id)
        ON DELETE SET NULL,

    CONSTRAINT fk_events_state
        FOREIGN KEY (state_id)
        REFERENCES states(id)
        ON DELETE SET NULL,

    CONSTRAINT fk_events_lga
        FOREIGN KEY (lga_id)
        REFERENCES lgas(id)
        ON DELETE SET NULL,

    -- =========================================================
    -- Validation
    -- =========================================================
    CONSTRAINT events_title_nonblank
        CHECK (BTRIM(title) <> ''),

    CONSTRAINT events_description_nonblank
        CHECK (BTRIM(description) <> ''),

    CONSTRAINT events_type_nonblank
        CHECK (BTRIM(event_type) <> ''),

    CONSTRAINT events_venue_nonblank
        CHECK (BTRIM(venue) <> ''),

    CONSTRAINT events_date_order_check
        CHECK (
            end_date IS NULL
            OR end_date >= start_date
        ),

    CONSTRAINT events_registration_link_check
        CHECK (
            registration_link IS NULL
            OR BTRIM(registration_link) <> ''
        ),

    CONSTRAINT events_max_participants_check
        CHECK (
            max_participants IS NULL
            OR max_participants > 0
        ),

    CONSTRAINT events_status_check
        CHECK (
            status IN (
                'upcoming',
                'ongoing',
                'completed',
                'cancelled'
            )
        )
);


-- =============================================================
-- EVENT INDEXES
-- =============================================================

CREATE INDEX IF NOT EXISTS idx_events_organization_id
ON events(organization_id);

CREATE INDEX IF NOT EXISTS idx_events_created_by
ON events(created_by);

CREATE INDEX IF NOT EXISTS idx_events_community_id
ON events(community_id);

CREATE INDEX IF NOT EXISTS idx_events_state_id
ON events(state_id);

CREATE INDEX IF NOT EXISTS idx_events_lga_id
ON events(lga_id);

CREATE INDEX IF NOT EXISTS idx_events_start_date
ON events(start_date);

CREATE INDEX IF NOT EXISTS idx_events_event_type
ON events(event_type);

CREATE INDEX IF NOT EXISTS idx_events_status
ON events(status);


-- =============================================================
-- EVENT REGISTRATIONS
-- =============================================================

CREATE TABLE IF NOT EXISTS event_registrations (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    event_id INTEGER NOT NULL,

    user_id INTEGER NOT NULL,

    status TEXT NOT NULL DEFAULT 'registered',

    registered_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- =========================================================
    -- Relationships
    -- =========================================================
    CONSTRAINT fk_event_registrations_event
        FOREIGN KEY (event_id)
        REFERENCES events(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_event_registrations_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    -- =========================================================
    -- Prevent duplicate registration
    -- =========================================================
    CONSTRAINT unique_event_registration
        UNIQUE (event_id, user_id),

    -- =========================================================
    -- Validation
    -- =========================================================
    CONSTRAINT event_registration_status_check
        CHECK (
            status IN (
                'registered',
                'attended',
                'cancelled'
            )
        )
);


-- =============================================================
-- EVENT REGISTRATION INDEXES
-- =============================================================

CREATE INDEX IF NOT EXISTS idx_event_registrations_event_id
ON event_registrations(event_id);

CREATE INDEX IF NOT EXISTS idx_event_registrations_user_id
ON event_registrations(user_id);

CREATE INDEX IF NOT EXISTS idx_event_registrations_status
ON event_registrations(status);