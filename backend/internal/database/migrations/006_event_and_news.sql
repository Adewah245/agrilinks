-- ============================================
-- NEWS / ANNOUNCEMENTS
-- ============================================

CREATE TABLE IF NOT EXISTS announcements (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    organization_id INTEGER,

    created_by INTEGER NOT NULL,

    title TEXT NOT NULL,

    content TEXT NOT NULL,

    category TEXT NOT NULL,

    image_url TEXT,

    status TEXT NOT NULL DEFAULT 'draft',

    published_at TIMESTAMP,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,


    CONSTRAINT fk_announcements_organization
        FOREIGN KEY (organization_id)
        REFERENCES organizations(id)
        ON DELETE SET NULL,


    CONSTRAINT fk_announcements_creator
        FOREIGN KEY (created_by)
        REFERENCES users(id)
        ON DELETE CASCADE,


    CONSTRAINT announcements_status_check
        CHECK (
            status IN (
                'draft',
                'published',
                'archived'
            )
        )
);


CREATE INDEX IF NOT EXISTS idx_announcements_category
ON announcements(category);


CREATE INDEX IF NOT EXISTS idx_announcements_status
ON announcements(status);


CREATE INDEX IF NOT EXISTS idx_announcements_published
ON announcements(published_at);



-- ============================================
-- AGRICULTURAL EVENTS
-- ============================================

CREATE TABLE IF NOT EXISTS events (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,


    organization_id INTEGER,


    created_by INTEGER NOT NULL,


    title TEXT NOT NULL,


    description TEXT NOT NULL,


    event_type TEXT NOT NULL,


    venue TEXT NOT NULL,


    community TEXT,


    state_id INTEGER,


    lga_id INTEGER,


    start_date TIMESTAMP NOT NULL,


    end_date TIMESTAMP,


    registration_required BOOLEAN NOT NULL DEFAULT FALSE,


    registration_link TEXT,


    max_participants INTEGER,


    status TEXT NOT NULL DEFAULT 'upcoming',


    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,


    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,


    CONSTRAINT fk_events_organization
        FOREIGN KEY (organization_id)
        REFERENCES organizations(id)
        ON DELETE SET NULL,


    CONSTRAINT fk_events_creator
        FOREIGN KEY (created_by)
        REFERENCES users(id)
        ON DELETE CASCADE,


    CONSTRAINT fk_events_state
        FOREIGN KEY (state_id)
        REFERENCES states(id)
        ON DELETE SET NULL,


    CONSTRAINT fk_events_lga
        FOREIGN KEY (lga_id)
        REFERENCES lgas(id)
        ON DELETE SET NULL,


    CONSTRAINT events_status_check
        CHECK (
            status IN (
                'upcoming',
                'ongoing',
                'completed',
                'cancelled'
            )
        )
);


CREATE INDEX IF NOT EXISTS idx_events_state
ON events(state_id);


CREATE INDEX IF NOT EXISTS idx_events_lga
ON events(lga_id);


CREATE INDEX IF NOT EXISTS idx_events_date
ON events(start_date);


CREATE INDEX IF NOT EXISTS idx_events_type
ON events(event_type);



-- ============================================
-- EVENT REGISTRATION
-- ============================================

CREATE TABLE IF NOT EXISTS event_registrations (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,


    event_id INTEGER NOT NULL,


    user_id INTEGER NOT NULL,


    status TEXT NOT NULL DEFAULT 'registered',


    registered_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,


    CONSTRAINT fk_event_registration_event
        FOREIGN KEY (event_id)
        REFERENCES events(id)
        ON DELETE CASCADE,


    CONSTRAINT fk_event_registration_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE,


    CONSTRAINT unique_event_registration
        UNIQUE(event_id, user_id),


    CONSTRAINT event_registration_status_check
        CHECK (
            status IN (
                'registered',
                'attended',
                'cancelled'
            )
        )
);


CREATE INDEX IF NOT EXISTS idx_event_registration_event
ON event_registrations(event_id);


CREATE INDEX IF NOT EXISTS idx_event_registration_user
ON event_registrations(user_id);