CREATE TABLE IF NOT EXISTS farm_economics (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    farming_activity_id INTEGER NOT NULL,

    recorded_by INTEGER NOT NULL,

    record_type TEXT NOT NULL,

    amount NUMERIC(20,2),
    quantity DOUBLE PRECISION,
    unit TEXT,

    price_per_unit NUMERIC(20,2),
    currency TEXT NOT NULL DEFAULT 'NGN',

    description TEXT,

    recorded_date DATE NOT NULL DEFAULT CURRENT_DATE,

    metadata JSONB,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    FOREIGN KEY (farming_activity_id)
        REFERENCES farming_activities(id)
        ON DELETE CASCADE,

    FOREIGN KEY (recorded_by)
        REFERENCES users(id)
        ON DELETE RESTRICT,

    CHECK (TRIM(record_type) <> ''),

    CHECK (
        record_type IN (
            'revenue',
            'sale',
            'valuation',
            'other'
        )
    ),

    CHECK (
        amount IS NULL
        OR amount >= 0
    ),

    CHECK (
        quantity IS NULL
        OR quantity > 0
    ),

    CHECK (
        price_per_unit IS NULL
        OR price_per_unit >= 0
    ),

    CHECK (
        quantity IS NULL
        OR unit IS NOT NULL
    ),

    CHECK (
        unit IS NULL
        OR TRIM(unit) <> ''
    ),

    CHECK (
        TRIM(currency) <> ''
    ),

    CHECK (
        description IS NULL
        OR TRIM(description) <> ''
    )
);

CREATE INDEX IF NOT EXISTS idx_farm_economics_activity
    ON farm_economics(farming_activity_id);

CREATE INDEX IF NOT EXISTS idx_farm_economics_recorded_by
    ON farm_economics(recorded_by);

CREATE INDEX IF NOT EXISTS idx_farm_economics_type
    ON farm_economics(record_type);

CREATE INDEX IF NOT EXISTS idx_farm_economics_date
    ON farm_economics(recorded_date);

CREATE INDEX IF NOT EXISTS idx_farm_economics_activity_date
    ON farm_economics(farming_activity_id, recorded_date);