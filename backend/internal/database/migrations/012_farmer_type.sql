CREATE TABLE IF NOT EXISTS farming_types (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    slug TEXT NOT NULL UNIQUE,
    description TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);


CREATE TABLE IF NOT EXISTS farmer_farming_types (
    farmer_id INTEGER NOT NULL,
    farming_type_id INTEGER NOT NULL,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (farmer_id, farming_type_id),

    CONSTRAINT fk_farmer_farming_types_farmer
        FOREIGN KEY (farmer_id)
        REFERENCES farmers(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_farmer_farming_types_type
        FOREIGN KEY (farming_type_id)
        REFERENCES farming_types(id)
        ON DELETE CASCADE
);


CREATE INDEX IF NOT EXISTS idx_farmer_farming_types_farmer
ON farmer_farming_types(farmer_id);


CREATE INDEX IF NOT EXISTS idx_farmer_farming_types_type
ON farmer_farming_types(farming_type_id);


