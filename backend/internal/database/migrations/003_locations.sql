CREATE TABLE IF NOT EXISTS states (

```
id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

name TEXT UNIQUE NOT NULL
```

);

CREATE TABLE IF NOT EXISTS lgas (

```
id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

state_id INTEGER NOT NULL,

name TEXT NOT NULL,

FOREIGN KEY (state_id)
    REFERENCES states(id)
    ON DELETE CASCADE,

CONSTRAINT unique_lga_per_state
    UNIQUE (state_id, name)
```

);

CREATE TABLE IF NOT EXISTS communities (

```
id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

lga_id INTEGER NOT NULL,

name TEXT NOT NULL,

FOREIGN KEY (lga_id)
    REFERENCES lgas(id)
    ON DELETE CASCADE,

CONSTRAINT unique_community_per_lga
    UNIQUE (lga_id, name)
```

);

CREATE INDEX IF NOT EXISTS idx_lgas_state_id
ON lgas(state_id);

CREATE INDEX IF NOT EXISTS idx_communities_lga_id
ON communities(lga_id);
