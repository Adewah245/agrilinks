CREATE TABLE IF NOT EXISTS farm_stock (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    farming_activity_id INTEGER NOT NULL,

    recorded_by INTEGER NOT NULL,

    stock_name TEXT NOT NULL,

    stock_type TEXT NOT NULL,

    quantity DOUBLE PRECISION NOT NULL,

    unit TEXT NOT NULL,

    status TEXT NOT NULL DEFAULT 'available',

    location TEXT,

    notes TEXT,

    metadata JSONB,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    FOREIGN KEY (farming_activity_id)
        REFERENCES farming_activities(id)
        ON DELETE CASCADE,

    FOREIGN KEY (recorded_by)
        REFERENCES users(id)
        ON DELETE RESTRICT,

    CHECK (TRIM(stock_name) <> ''),

    CHECK (
        stock_type IN (
            'animal',
            'crop',
            'fish',
            'poultry',
            'egg',
            'milk',
            'honey',
            'harvested_produce',
            'seedling',
            'bee_colony',
            'other'
        )
    ),

    CHECK (quantity >= 0),

    CHECK (TRIM(unit) <> ''),

    CHECK (
        status IN (
            'available',
            'reserved',
            'sold',
            'consumed',
            'lost',
            'damaged',
            'expired',
            'transferred'
        )
    ),

    CHECK (
        location IS NULL
        OR TRIM(location) <> ''
    ),

    CHECK (
        notes IS NULL
        OR TRIM(notes) <> ''
    )
);

CREATE INDEX IF NOT EXISTS idx_farm_stock_activity
    ON farm_stock(farming_activity_id);

CREATE INDEX IF NOT EXISTS idx_farm_stock_recorded_by
    ON farm_stock(recorded_by);

CREATE INDEX IF NOT EXISTS idx_farm_stock_type
    ON farm_stock(stock_type);

CREATE INDEX IF NOT EXISTS idx_farm_stock_status
    ON farm_stock(status);

CREATE INDEX IF NOT EXISTS idx_farm_stock_name
    ON farm_stock(stock_name);

CREATE INDEX IF NOT EXISTS idx_farm_stock_activity_status
    ON farm_stock(farming_activity_id, status);