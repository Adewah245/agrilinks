-- =============================================================
-- 005_organizations.sql
--
-- Defines organizations and their relationship with Agro-Shield
-- users.
--
-- Organizations may include:
--   - Agricultural organizations
--   - Cooperatives
--   - NGOs
--   - Government agencies
--   - Ministries
--   - Educational/training organizations
--   - Other agricultural partners
--
-- Organization membership is separate from a user's platform role.
-- =============================================================


-- =============================================================
-- ORGANIZATIONS
-- =============================================================

CREATE TABLE IF NOT EXISTS organizations (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- =========================================================
    -- Identity
    -- =========================================================
    name TEXT NOT NULL,

    organization_type TEXT NOT NULL,

    description TEXT,

    logo_url TEXT,

    -- =========================================================
    -- Location
    -- =========================================================
    state_id INTEGER,

    lga_id INTEGER,

    -- =========================================================
    -- Verification
    -- =========================================================
    verified BOOLEAN NOT NULL DEFAULT FALSE,

    -- =========================================================
    -- Timestamps
    -- =========================================================
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- =========================================================
    -- Relationships
    -- =========================================================
    CONSTRAINT fk_organizations_state
        FOREIGN KEY (state_id)
        REFERENCES states(id)
        ON DELETE SET NULL,

    CONSTRAINT fk_organizations_lga
        FOREIGN KEY (lga_id)
        REFERENCES lgas(id)
        ON DELETE SET NULL,

    -- =========================================================
    -- Validation
    -- =========================================================
    CONSTRAINT organizations_name_nonblank
        CHECK (BTRIM(name) <> ''),

    CONSTRAINT organizations_type_nonblank
        CHECK (BTRIM(organization_type) <> '')
);


-- =============================================================
-- ORGANIZATION INDEXES
-- =============================================================

CREATE INDEX IF NOT EXISTS idx_organizations_type
ON organizations(organization_type);

CREATE INDEX IF NOT EXISTS idx_organizations_state_id
ON organizations(state_id);

CREATE INDEX IF NOT EXISTS idx_organizations_lga_id
ON organizations(lga_id);

CREATE INDEX IF NOT EXISTS idx_organizations_verified
ON organizations(verified);


-- =============================================================
-- ORGANIZATION MEMBERS
-- =============================================================

CREATE TABLE IF NOT EXISTS organization_members (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    organization_id INTEGER NOT NULL,

    user_id INTEGER NOT NULL,

    position TEXT,

    member_role TEXT NOT NULL DEFAULT 'staff',

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- =========================================================
    -- Relationships
    -- =========================================================
    CONSTRAINT fk_organization_members_organization
        FOREIGN KEY (organization_id)
        REFERENCES organizations(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_organization_members_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    -- =========================================================
    -- A user cannot be added to the same organization twice.
    -- =========================================================
    CONSTRAINT unique_organization_member
        UNIQUE (organization_id, user_id),

    -- =========================================================
    -- Validation
    -- =========================================================
    CONSTRAINT organization_members_role_nonblank
        CHECK (BTRIM(member_role) <> '')
);


-- =============================================================
-- ORGANIZATION MEMBER INDEXES
-- =============================================================

CREATE INDEX IF NOT EXISTS idx_organization_members_organization_id
ON organization_members(organization_id);

CREATE INDEX IF NOT EXISTS idx_organization_members_user_id
ON organization_members(user_id);

CREATE INDEX IF NOT EXISTS idx_organization_members_role
ON organization_members(member_role);