-- ============================================================
-- 028_farming_monitoring.sql
-- General Farming Activity Monitoring
-- Supports all farming types
-- ============================================================

CREATE TABLE IF NOT EXISTS farming_monitoring (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    farming_activity_id INTEGER NOT NULL,

    recorded_by INTEGER NOT NULL,

    recorded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    stage TEXT,

    status TEXT,

    progress_percentage DOUBLE PRECISION,

    observation TEXT,

    measurement_value DOUBLE PRECISION,

    measurement_unit TEXT,

    health_status TEXT,

    environmental_condition TEXT,

    notes TEXT,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_farming_monitoring_activity
        FOREIGN KEY (farming_activity_id)
        REFERENCES farming_activities(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_farming_monitoring_recorder
        FOREIGN KEY (recorded_by)
        REFERENCES users(id)
        ON DELETE RESTRICT,

    CONSTRAINT farming_monitoring_stage_check
        CHECK (
            stage IS NULL
            OR BTRIM(stage) <> ''
        ),

    CONSTRAINT farming_monitoring_status_check
        CHECK (
            status IS NULL
            OR BTRIM(status) <> ''
        ),

    CONSTRAINT farming_monitoring_progress_check
        CHECK (
            progress_percentage IS NULL
            OR (
                progress_percentage >= 0
                AND progress_percentage <= 100
            )
        ),

    CONSTRAINT farming_monitoring_observation_check
        CHECK (
            observation IS NULL
            OR BTRIM(observation) <> ''
        ),

    CONSTRAINT farming_monitoring_measurement_check
        CHECK (
            measurement_value IS NULL
            OR measurement_unit IS NOT NULL
        ),

    CONSTRAINT farming_monitoring_measurement_unit_check
        CHECK (
            measurement_unit IS NULL
            OR BTRIM(measurement_unit) <> ''
        ),

    CONSTRAINT farming_monitoring_health_status_check
        CHECK (
            health_status IS NULL
            OR BTRIM(health_status) <> ''
        ),

    CONSTRAINT farming_monitoring_environment_check
        CHECK (
            environmental_condition IS NULL
            OR BTRIM(environmental_condition) <> ''
        ),

    CONSTRAINT farming_monitoring_notes_check
        CHECK (
            notes IS NULL
            OR BTRIM(notes) <> ''
        )
);


CREATE INDEX IF NOT EXISTS idx_farming_monitoring_activity_id
    ON farming_monitoring(farming_activity_id);

CREATE INDEX IF NOT EXISTS idx_farming_monitoring_recorded_by
    ON farming_monitoring(recorded_by);

CREATE INDEX IF NOT EXISTS idx_farming_monitoring_recorded_at
    ON farming_monitoring(recorded_at);

CREATE INDEX IF NOT EXISTS idx_farming_monitoring_stage
    ON farming_monitoring(stage);

CREATE INDEX IF NOT EXISTS idx_farming_monitoring_health_status
    ON farming_monitoring(health_status);

CREATE INDEX IF NOT EXISTS idx_farming_monitoring_activity_time
    ON farming_monitoring(farming_activity_id, recorded_at DESC);