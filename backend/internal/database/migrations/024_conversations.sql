CREATE TABLE IF NOT EXISTS conversations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    conversation_type TEXT NOT NULL DEFAULT 'private',

    title TEXT,

    created_by INTEGER,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_conversations_created_by
        FOREIGN KEY (created_by)
        REFERENCES users(id)
        ON DELETE SET NULL,

    CONSTRAINT conversations_type_check
        CHECK (
            conversation_type IN (
                'private',
                'group'
            )
        ),

    CONSTRAINT conversations_title_check
        CHECK (
            title IS NULL
            OR BTRIM(title) <> ''
        )
);


CREATE INDEX IF NOT EXISTS idx_conversations_type
    ON conversations(conversation_type);

CREATE INDEX IF NOT EXISTS idx_conversations_created_by
    ON conversations(created_by);

CREATE INDEX IF NOT EXISTS idx_conversations_created_at
    ON conversations(created_at);

CREATE INDEX IF NOT EXISTS idx_conversations_updated_at
    ON conversations(updated_at);